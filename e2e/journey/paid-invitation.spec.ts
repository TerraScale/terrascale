import { randomBytes } from 'node:crypto';
import { Audit, auditedContext, test, expect } from '../support/audit';
import { hostedReady, onboard, onHosted, signInWithPassword } from '../support/hosted';
import { nextMail } from '../support/inbox';
import type { PaidJourney } from '../support/paid';
import { enterSecret } from '../support/secret';
import { shell } from '../support/shell';
import { dash, desktop } from '../support/stack';
import { journey, ownerSession, saveCookies, saveSecret, setupFinished } from '../support/state';

test.beforeAll(({}, info) => {
  expect(setupFinished(info), 'setup did not finish').toBe(true);
});

test('the Pro owner invites a second user, who signs up through the emailed link, accepts, is listed with their role and chooses between their two organizations', async ({ browser }, info) => {
  const owner = journey<PaidJourney>();
  const email = `member-${owner.runId}${Date.now().toString(36)}@example.com`;
  const password = randomBytes(24).toString('base64url');
  saveSecret('member-password', password);

  const ownerContext = await auditedContext(browser, { viewport: desktop, storageState: ownerSession() });
  const ownerPage = await ownerContext.newPage();
  const ownerAudit = new Audit(ownerPage, info);
  await ownerPage.goto(`${dash}/organization?tab=members`);
  await ownerPage.locator('.ts-org-header').getByRole('button', { name: 'Invite', exact: true }).click();
  await expect(ownerPage.locator('dialog#team-invite')).toBeVisible();
  await ownerPage.locator('#invite-email').fill(email);
  await ownerPage.locator('#invite-role').selectOption('member');
  await ownerPage.locator('#team-invite').locator('button[type=submit]').click();
  const invited = ownerPage.locator('#team-invitations tr').filter({ hasText: email });
  await expect(invited).toHaveCount(1);
  await expect(invited).toContainText('Member');
  await expect(invited).toContainText('Pending');
  await shell(ownerPage, owner);
  await ownerAudit.check('invitation sent on Pro');

  const mail = await nextMail(email, 0);
  const link = /https:\/\/dash\.terrascale\.tech\/invitations\/[A-Za-z0-9_-]+/.exec(mail.text)?.[0] ?? '';
  expect(link, 'the invitation email links to its dashboard page').not.toBe('');
  saveSecret('invitation-link', link.split('/').at(-1) ?? '');
  expect(mail.from, 'invitation sender').toBe('no-reply@terrascale.tech');
  expect(mail.subject, 'invitation subject').toContain(owner.organizationName);

  const member = await auditedContext(browser, { viewport: desktop });
  const page = await member.newPage();
  const audit = new Audit(page, info);
  await page.goto(link);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Sign in to view this invitation');
  await audit.check('invitation signed out');
  await page.getByRole('link', { name: 'Sign in', exact: true }).click();
  await page.waitForURL(onHosted('sign-in'));
  await hostedReady(page);
  await audit.check('member sign-in from the invitation');
  await page.getByRole('link', { name: 'Create account', exact: true }).click();
  await page.waitForURL(onHosted('sign-up'));
  await hostedReady(page);
  await audit.check('member sign-up from the invitation');
  await page.locator('#sign-up-email').fill(email);
  await enterSecret(page.locator('#sign-up-password'), password);
  await page.locator('form[action="/ui/terrascale/sign-up"] button[type=submit]').click();
  await expect(page).toHaveTitle('Verify your email · TerraScale');
  await audit.check('member sign-up verify');
  const code = /^\s*(\d{6})\s*$/m.exec((await nextMail(email, 1)).text)?.[1] ?? '';
  expect(code, 'a 6-digit code on its own line').toMatch(/^\d{6}$/);
  await enterSecret(page.locator('#sign-up-code-digit'), code);
  await page.getByRole('button', { name: 'Verify email' }).click();
  await page.waitForURL((url) => url.origin === dash && url.pathname === new URL(link).pathname);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(`Join ${owner.organizationName}`);
  await expect(page.locator('main .ts-meta').first()).toContainText(`${email} · member`);
  await audit.check('invitation for the invited user');

  await page.getByRole('button', { name: 'Accept invitation', exact: true }).click();
  await page.waitForURL((url) => url.origin === dash && url.pathname === '/organization' && url.searchParams.get('invitation') === 'accepted');
  const members = page.locator('#team-members tbody tr');
  await expect(members).toHaveCount(2);
  await expect(members.filter({ hasText: owner.email })).toContainText('Organization Owner');
  await expect(members.filter({ hasText: email })).toContainText('Member');
  await expect(page.locator(`[data-active-organization-id="${owner.organizationId}"]`)).toHaveText(`Current organization: ${owner.organizationName}`);
  await audit.check('invited user in the Pro organization');

  await page.locator('.ts-account-trigger').click();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.waitForLoadState('load');
  await page.goto(`${dash}/login`);
  await signInWithPassword(page, audit, email, password, 'invited user');
  await page.waitForURL((url) => url.origin === dash && url.pathname === '/onboarding');
  const memberName = `Member ${owner.runId}`;
  const memberProject = `Member project ${owner.runId}`;
  await onboard(page, audit, memberName, memberProject, 'invited user');
  const personal = new URL(page.url()).searchParams;
  await shell(page, { email, displayName: memberName, organizationId: personal.get('organizationId') ?? '', organizationName: 'Personal', projectId: personal.get('projectId') ?? '', projectName: memberProject });
  await audit.check('invited user on the Personal overview after onboarding');
  await page.locator('.ts-account-trigger').click();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.waitForLoadState('load');
  await page.goto(`${dash}/login`);
  await signInWithPassword(page, audit, email, password, 'invited user again');
  await page.waitForURL((url) => url.origin === dash && url.pathname === '/organizations/choose');
  const choices = page.locator('main').getByRole('button');
  await expect(choices.filter({ hasText: owner.organizationName })).toHaveCount(1);
  await expect(choices.filter({ hasText: 'Personal' })).toHaveCount(1);
  await audit.check('organization choice of the invited user');
  await choices.filter({ hasText: owner.organizationName }).click();
  await page.waitForURL((url) => url.origin === dash && url.pathname === '/');
  await expect(page.locator(`[data-active-organization-id="${owner.organizationId}"]`)).toHaveText(`Current organization: ${owner.organizationName}`);
  await audit.check('invited user on the Pro organization overview');
  await audit.finish();
  await saveCookies(member);
  await member.close();

  await ownerPage.goto(`${dash}/organization?tab=members`);
  const rows = ownerPage.locator('#team-members tbody tr');
  await expect(rows).toHaveCount(2);
  const memberRow = rows.filter({ hasText: email });
  await expect(memberRow.locator('select.ts-access-role')).toHaveValue('member');
  await expect(rows.filter({ hasText: owner.email })).toContainText('Organization Owner');
  await expect(ownerPage.locator('#team-invitations tr').filter({ hasText: email })).toContainText('Accepted');
  await ownerAudit.check('Pro members with the invited user');
  await memberRow.getByRole('button', { name: 'Remove access', exact: true }).click();
  const remove = ownerPage.locator('dialog[open]');
  await expect(remove).toBeVisible();
  await ownerAudit.check('remove the invited user dialog');
  await remove.getByRole('button', { name: 'Remove access', exact: true }).click();
  await expect(rows).toHaveCount(1);
  await expect(rows).toContainText(owner.email);
  await ownerAudit.check('Pro members after the removal');
  await ownerAudit.finish();
  await saveCookies(ownerContext);
  await ownerContext.close();
});
