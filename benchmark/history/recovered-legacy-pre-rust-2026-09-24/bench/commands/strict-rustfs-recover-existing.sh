#!/usr/bin/env bash
set -Eeuo pipefail
IFS=$'\n\t'

# Existing-prefix RustFS recovery probe.
#
# This wrapper never deletes objects. The benchmark process validates the
# source receipt and deletes only its owned source engine root after the fresh
# recovery output has been admitted.
#
#   preflight --source-run-dir PATH [options]
#   launch    --source-run-dir PATH [options]
#   verify    --run-dir PATH

readonly SCRIPT_PATH="$(readlink -f "$BASH_SOURCE")"
readonly SCRIPT_DIR="$(dirname "$SCRIPT_PATH")"
readonly LAUNCH_ENV_PARSER="$SCRIPT_DIR/load-launch-env.sh"
source "$LAUNCH_ENV_PARSER"
readonly BENCH_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
readonly RECEIPTS_DIR="$BENCH_ROOT/bench/receipts"
readonly DEFAULT_DOTNET_BIN="/home/mariogk/.local/share/mise/dotnet-root/dotnet"
readonly DEFAULT_CREDENTIALS_FILE="/run/user/1000/terrabase-rustfs-credentials.sh"
readonly DEFAULT_RUSTFS_CONTAINER="terrabase-rustfs-20260922"
readonly DEFAULT_ENDPOINT="http://127.0.0.1:19000"
readonly DEFAULT_BUCKET="terrabase-tiered"
readonly RECOVERY_CACHE_BYTES=16777216
readonly RECOVERY_MAX_LOCAL_STORAGE_BYTES=85899345920
readonly RECOVERY_MIN_FREE_SPACE_BYTES=107374182400
readonly FREE_FLOOR=107374182400
# The recovery may consume up to 85 GiB on the fresh root. Require the
# benchmark-owned source root to be reclaimable before admitting the run and
# retain the established 250 GiB post-reclaim budget for the host.
readonly PREFLIGHT_FREE_BYTES=268435456000

MODE=preflight
SOURCE_RUN_DIR=
RUN_DIR=
MANIFEST=
MANIFEST_EXPLICIT=0
DOTNET_BIN="$DEFAULT_DOTNET_BIN"
DOTNET_EXPLICIT=0
CREDENTIALS_FILE="$DEFAULT_CREDENTIALS_FILE"
RUSTFS_CONTAINER="$DEFAULT_RUSTFS_CONTAINER"
ENDPOINT="$DEFAULT_ENDPOINT"
BUCKET="$DEFAULT_BUCKET"
RUN_LABEL=""

SOURCE_RECEIPT=
SOURCE_ENGINE=
SOURCE_RECEIPT_SHA=
SOURCE_RECORDS=
SOURCE_PREFIX=
SOURCE_BATCH=
SOURCE_PAYLOAD_BYTES=
SOURCE_PAYLOAD_MODE=
SOURCE_SEED=
SOURCE_REGION=
SOURCE_S3_ENDPOINT=
SOURCE_DATABASE_ID=
SOURCE_WRITER_ID=
SOURCE_JOURNAL_FRAME_PREFIX=
SOURCE_SOURCE_DIRTY=
SOURCE_BENCH_DLL=
SOURCE_BENCH_SHA=
SOURCE_COMMIT=
SOURCE_TREE_DIGEST=
SOURCE_WORKTREE_DIGEST=
SOURCE_MANIFEST=
SOURCE_RUN_OUTPUT=
SOURCE_UNIT=
SOURCE_MONITOR_UNIT=
UNIT=
EXACT_SCAN_REQUESTED=0
SOURCE_ENGINE_BYTES=0
SOURCE_FREE_BYTES=0
SOURCE_FREE_AFTER_RECLAIM_BYTES=0

die() {
    printf 'strict-rustfs-recover-existing: %s\n' "$*" >&2
    exit 1
}

usage() {
    cat <<'EOF'
Usage:
  strict-rustfs-recover-existing.sh preflight --source-run-dir PATH [options]
  strict-rustfs-recover-existing.sh launch --source-run-dir PATH [options]
  strict-rustfs-recover-existing.sh verify --run-dir PATH

Options:
  --source-run-dir PATH   Completed strict ingest run containing launch.env.
  --run-dir PATH          Existing recovery run directory for verify.
  --manifest PATH         Frozen release manifest; defaults to source launch.env.
  --run-label LABEL       Recovery run label; defaults to source label + recovery.
  --dotnet PATH           .NET runtime; defaults to the source launch value.
  --credentials-file PATH Private RustFS credential file.
  --endpoint URL           RustFS endpoint.
  --bucket NAME            RustFS bucket.
  --exact-scan              Require and verify an ordered exact scan of every recovered record.

The default launch performs sampled remote-journal root-loss recovery and
records verificationScope=sampled-remote-journal-recovery. A source run with
100M or more records must be launched with --exact-scan; smaller smoke runs
may omit it and remain explicitly sampled. Preflight counts the owned source
engine as reclaimable space and requires current free space of at least 100 GiB
plus that root to reach the 250 GiB post-reclaim budget.
EOF
}

require_commands() {
    local command_name
    for command_name in awk cmp curl date df du jq nice podman readlink sha256sum stat systemctl systemd-run; do
        command -v "$command_name" >/dev/null 2>&1 || die "required command is missing: $command_name"
    done
}

load_source() {
    [[ -n "$SOURCE_RUN_DIR" ]] || die "--source-run-dir is required"
    [[ ! -L "$SOURCE_RUN_DIR" ]] || die "source run directory must not be a symlink"
    SOURCE_RUN_DIR="$(readlink -f "$SOURCE_RUN_DIR")"
    [[ -d "$SOURCE_RUN_DIR" && ! -L "$SOURCE_RUN_DIR" ]] || die "source run directory is not a regular directory: $SOURCE_RUN_DIR"
    [[ -f "$SOURCE_RUN_DIR/launch.env" && ! -L "$SOURCE_RUN_DIR/launch.env" ]] || die "source launch.env is missing"
    # launch.env is generated by strict-rustfs-ingest.sh. Parse its allowlisted
    # printf %q metadata without executing receipt-controlled shell text. Keep
    # all source values in dedicated variables before the recovery output is
    # selected. The recovery mode flag comes from this invocation and must not
    # be overridden by source metadata.
    local requested_exact_scan="$EXACT_SCAN_REQUESTED"
    local requested_manifest="$MANIFEST"
    local requested_dotnet="$DOTNET_BIN"
    local manifest_was_explicit="$MANIFEST_EXPLICIT"
    local dotnet_was_explicit="$DOTNET_EXPLICIT"
    load_launch_env_file "$SOURCE_RUN_DIR/launch.env" \
        RUN_ID OUTPUT PREFIX UNIT MONITOR_UNIT MANIFEST FROZEN_MANIFEST_PATH \
        FROZEN_MANIFEST_SHA256 BINARY_CLOSURE BENCH_DLL BENCH_SHA256 \
        SOURCE_REPOSITORY SOURCE_COMMIT SOURCE_TREE_DIGEST SOURCE_WORKTREE_DIGEST \
        SOURCE_DIRTY EXPECTED_RECORDS RUN_LABEL DOTNET_BIN S3_ENDPOINT S3_BUCKET \
        LAUNCH_EPOCH || die "source launch.env failed strict metadata validation"
    EXACT_SCAN_REQUESTED="$requested_exact_scan"
    MANIFEST_EXPLICIT="$manifest_was_explicit"
    DOTNET_EXPLICIT="$dotnet_was_explicit"
    SOURCE_RUN_OUTPUT="$OUTPUT"
    SOURCE_UNIT="$UNIT"
    SOURCE_MONITOR_UNIT="${MONITOR_UNIT:-}"
    SOURCE_BENCH_DLL="$BENCH_DLL"
    SOURCE_BENCH_SHA="$BENCH_SHA256"
    SOURCE_COMMIT="$SOURCE_COMMIT"
    SOURCE_TREE_DIGEST="$SOURCE_TREE_DIGEST"
    SOURCE_WORKTREE_DIGEST="$SOURCE_WORKTREE_DIGEST"
    SOURCE_SOURCE_DIRTY="$SOURCE_DIRTY"
    SOURCE_MANIFEST="$MANIFEST"
    [[ -n "$SOURCE_REPOSITORY" && "$SOURCE_COMMIT" =~ ^[0-9a-fA-F]{40}$ &&
       "$SOURCE_TREE_DIGEST" =~ ^[0-9a-fA-F]{40}$ &&
       "$SOURCE_WORKTREE_DIGEST" =~ ^[0-9a-fA-F]{64}$ &&
       ("$SOURCE_SOURCE_DIRTY" == true || "$SOURCE_SOURCE_DIRTY" == false) ]] ||
        die "source launch.env lacks valid provenance identity"
    [[ "$SOURCE_RUN_OUTPUT" == "$SOURCE_RUN_DIR" ]] || die "source launch.env output does not match source run directory"
    local source_state monitor_state
    source_state="$(systemctl --user show "$SOURCE_UNIT" -p ActiveState --value 2>/dev/null || true)"
    monitor_state="$(systemctl --user show "$SOURCE_MONITOR_UNIT" -p ActiveState --value 2>/dev/null || true)"
    case "$source_state" in active|activating|deactivating) die "source benchmark unit is still active: $SOURCE_UNIT" ;; esac
    case "$monitor_state" in active|activating|deactivating) die "source monitor unit is still active: $SOURCE_MONITOR_UNIT" ;; esac
    SOURCE_RECEIPT="$SOURCE_RUN_DIR/tiered-rustfs-receipt.json"
    [[ -s "$SOURCE_RECEIPT" && ! -L "$SOURCE_RECEIPT" ]] || die "source tiered receipt is missing or a symlink"
    SOURCE_RECEIPT_SHA="$(sha256sum "$SOURCE_RECEIPT" | awk '{ print $1 }')"

    local status ingest records engine
    status="$(jq -r '.Status // empty' "$SOURCE_RECEIPT")"
    ingest="$(jq -r '.IngestOnly // false' "$SOURCE_RECEIPT")"
    records="$(jq -r '.TargetRecords // 0' "$SOURCE_RECEIPT")"
    engine="$(jq -r '.EngineRoot // empty' "$SOURCE_RECEIPT")"
    [[ "$status" == complete && "$ingest" == true && "$records" =~ ^[1-9][0-9]*$ ]] ||
        die "source receipt is not a complete ingest-only qualification"
    SOURCE_RECORDS="$records"
    SOURCE_ENGINE="$engine"
    [[ "$SOURCE_ENGINE" == "$SOURCE_RUN_DIR/engine" ]] || die "source receipt engine root is not source-owned"
    [[ -d "$SOURCE_ENGINE" && ! -L "$SOURCE_ENGINE" ]] ||
        die "source engine root is missing or a symlink"
    local source_engine_real
    source_engine_real="$(readlink -f -- "$SOURCE_ENGINE")"
    [[ "$source_engine_real" == "$SOURCE_ENGINE" ]] ||
        die "source engine root resolves outside its source-owned path"
    [[ -f "$SOURCE_ENGINE/wal" && ! -L "$SOURCE_ENGINE/wal" && -s "$SOURCE_ENGINE/wal" ]] ||
        die "source local WAL is missing, empty, or a symlink"

    if (( SOURCE_RECORDS >= 100000000 && EXACT_SCAN_REQUESTED != 1 )); then
        die "100M recovery requires --exact-scan"
    fi

    SOURCE_PREFIX="$(jq -r '.Prefix // empty' "$SOURCE_RECEIPT")"
    SOURCE_BATCH="$(jq -r '.Batch // 0' "$SOURCE_RECEIPT")"
    SOURCE_PAYLOAD_BYTES="$(jq -r '.PayloadBytes // 0' "$SOURCE_RECEIPT")"
    SOURCE_PAYLOAD_MODE="$(jq -r '.PayloadMode // empty' "$SOURCE_RECEIPT")"
    SOURCE_SEED="$(jq -r '.PayloadSeed // 0' "$SOURCE_RECEIPT")"
    SOURCE_REGION="$(jq -r '.Region // empty' "$SOURCE_RECEIPT")"
    SOURCE_S3_ENDPOINT="$(jq -r '.S3Endpoint // empty' "$SOURCE_RECEIPT")"
    SOURCE_DATABASE_ID="$(jq -r '.DatabaseId // empty' "$SOURCE_RECEIPT")"
    SOURCE_WRITER_ID="$(jq -r '.WriterId // empty' "$SOURCE_RECEIPT")"
    SOURCE_JOURNAL_FRAME_PREFIX="$(jq -r '.JournalFramePrefix // empty' "$SOURCE_RECEIPT")"
    [[ -n "$SOURCE_PREFIX" && "$SOURCE_BATCH" =~ ^[1-9][0-9]*$ && "$SOURCE_PAYLOAD_BYTES" =~ ^[1-9][0-9]*$ ]] || die "source receipt lacks recovery metadata"
    [[ -n "$SOURCE_PAYLOAD_MODE" && -n "$SOURCE_REGION" && -n "$SOURCE_S3_ENDPOINT" && -n "$SOURCE_DATABASE_ID" && -n "$SOURCE_WRITER_ID" && -n "$SOURCE_JOURNAL_FRAME_PREFIX" ]] || die "source receipt lacks journal identity metadata"
    jq -e '.RemoteObjects.ObjectCount == 0 and .RemoteObjects.TotalBytes == 0' "$SOURCE_RECEIPT" >/dev/null || die "source receipt contains sealed segment objects"

    if (( MANIFEST_EXPLICIT == 1 )); then
        MANIFEST="$requested_manifest"
    else
        MANIFEST="$SOURCE_MANIFEST"
    fi
    if (( DOTNET_EXPLICIT == 1 )); then
        DOTNET_BIN="$requested_dotnet"
    fi
}

load_manifest() {
    [[ -f "$MANIFEST" && ! -L "$MANIFEST" ]] || die "freeze manifest is missing: $MANIFEST"
    local closure manifest_sha
    closure="$(awk -F= '$1 == "binaryClosure" { print $2; exit }' "$MANIFEST")"
    [[ -n "$closure" && -d "$closure" ]] || die "freeze manifest binary closure is missing"
    local expected_dotnet_version actual_dotnet_version
    expected_dotnet_version="$(awk -F= '$1 == "dotnetVersion" { print $2; exit }' "$MANIFEST")"
    [[ -n "$expected_dotnet_version" ]] || die "freeze manifest has no dotnetVersion"
    [[ -x "$DOTNET_BIN" ]] || die ".NET runtime is not executable: $DOTNET_BIN"
    actual_dotnet_version="$("$DOTNET_BIN" --version)" || die "unable to query .NET runtime version"
    [[ "$actual_dotnet_version" == "$expected_dotnet_version" ]] ||
        die ".NET runtime mismatch: manifest=$expected_dotnet_version actual=$actual_dotnet_version"
    SOURCE_BENCH_DLL="$closure/TerraBase.Benchmarks.dll"
    manifest_sha="$(awk 'length($1) == 64 && $NF ~ /(^|\/)TerraBase[.]Benchmarks[.]dll$/ { print $1; exit }' "$MANIFEST")"
    [[ -n "$manifest_sha" ]] || die "freeze manifest has no benchmark hash"
    [[ -f "$SOURCE_BENCH_DLL" ]] || die "frozen benchmark assembly is missing"
    [[ "$(sha256sum "$SOURCE_BENCH_DLL" | awk '{ print $1 }')" == "$manifest_sha" ]] || die "frozen benchmark assembly hash mismatch"
    [[ "$manifest_sha" == "$SOURCE_BENCH_SHA" ]] || die "source run assembly does not match frozen manifest"
}

check_host() {
    [[ -r "$CREDENTIALS_FILE" ]] || die "RustFS credentials file is not readable"
    [[ "$(podman inspect --format '{{.State.Status}}' "$RUSTFS_CONTAINER" 2>/dev/null || true)" == running ]] || die "RustFS container is not running"
    local status
    status="$(curl --connect-timeout 2 --max-time 5 -sS -o /dev/null -w '%{http_code}' "$ENDPOINT" 2>/dev/null || true)"
    case "$status" in 200|400|403|405) ;; *) die "RustFS endpoint is unavailable: $ENDPOINT status=$status" ;; esac
    local free source_bytes source_filesystem receipts_filesystem
    free="$(df -B1 --output=avail "$RECEIPTS_DIR" | awk 'NR == 2 { print $1 }')"
    [[ "$free" =~ ^[0-9]+$ ]] || die "unable to read free space for $RECEIPTS_DIR"
    (( free >= FREE_FLOOR )) || die "free space $free is below the runtime free-space floor $FREE_FLOOR"

    receipts_filesystem="$(df --output=source "$RECEIPTS_DIR" | awk 'NR == 2 { print $1 }')"
    source_filesystem="$(df --output=source "$SOURCE_ENGINE" | awk 'NR == 2 { print $1 }')"
    [[ -n "$receipts_filesystem" && "$receipts_filesystem" == "$source_filesystem" ]] ||
        die "source engine and recovery output are on different filesystems; source bytes cannot be counted as reclaimable"

    source_bytes="$(du -sB1 -- "$SOURCE_ENGINE" | awk 'NR == 1 { print $1 }')"
    [[ "$source_bytes" =~ ^[0-9]+$ && "$source_bytes" -gt 0 ]] || die "unable to measure the reclaimable source engine root"
    SOURCE_ENGINE_BYTES="$source_bytes"
    SOURCE_FREE_BYTES="$free"
    SOURCE_FREE_AFTER_RECLAIM_BYTES=$((free + source_bytes))
    if (( SOURCE_FREE_AFTER_RECLAIM_BYTES < PREFLIGHT_FREE_BYTES )); then
        die "free space $free plus reclaimable source engine bytes $source_bytes is below the required post-reclaim budget $PREFLIGHT_FREE_BYTES (current free-space floor $FREE_FLOOR; source root deletion is counted as reclaimable)"
    fi

    local active_benchmark_units
    active_benchmark_units="$(systemctl --user list-units --type=service --state=active --no-legend --no-pager 'terrabase-*.service' 2>/dev/null |
        awk '$1 ~ /^terrabase-/ { print $1 }' || true)"
    [[ -z "$active_benchmark_units" ]] ||
        die "an active TerraBase benchmark service is running: $active_benchmark_units; wait for a quiet window"
}

prepare_identity() {
    [[ -n "$RUN_LABEL" ]] || RUN_LABEL="$(basename "$SOURCE_RUN_DIR")-recovery"
    [[ "$RUN_LABEL" =~ ^[[:alnum:]_.-]+$ ]] || die "run label contains unsafe characters"
    RUN_DIR="$RECEIPTS_DIR/$RUN_LABEL-$(date -u +%Y%m%dT%H%M%S%NZ)"
    UNIT="terrabase-$RUN_LABEL.service"
    [[ ! -e "$RUN_DIR" ]] || die "recovery output already exists: $RUN_DIR"
    [[ "$RUN_DIR" != "$SOURCE_RUN_DIR" && "$SOURCE_RUN_DIR" != "$RUN_DIR"/* && "$RUN_DIR" != "$SOURCE_RUN_DIR"/* ]] || die "recovery output must be a separate sibling root"
    systemctl --user show "$UNIT" -p LoadState --value 2>/dev/null | grep -q '^loaded$' && die "systemd unit already exists: $UNIT" || true
}

preflight() {
    require_commands
    load_source
    load_manifest
    check_host
    prepare_identity
    printf 'preflight=ok\nsource_run_dir=%s\nsource_receipt=%s\nrecords=%s\nrecovery_output=%s\nbenchmark_sha256=%s\nsource_engine_bytes=%s\nfree_bytes=%s\nfree_after_source_reclaim_bytes=%s\nrequired_post_reclaim_bytes=%s\n' \
        "$SOURCE_RUN_DIR" "$SOURCE_RECEIPT" "$SOURCE_RECORDS" "$RUN_DIR" "$SOURCE_BENCH_SHA" \
        "$SOURCE_ENGINE_BYTES" "$SOURCE_FREE_BYTES" "$SOURCE_FREE_AFTER_RECLAIM_BYTES" "$PREFLIGHT_FREE_BYTES"
}

write_launch_env() {
    mkdir -m 700 "$RUN_DIR"
    {
        printf 'OUTPUT=%q\n' "$RUN_DIR"
        printf 'RUN_DIR=%q\n' "$RUN_DIR"
        printf 'UNIT=%q\n' "$UNIT"
        printf 'SOURCE_RUN_DIR=%q\n' "$SOURCE_RUN_DIR"
        printf 'SOURCE_RECEIPT=%q\n' "$SOURCE_RECEIPT"
        printf 'SOURCE_RECEIPT_SHA=%q\n' "$SOURCE_RECEIPT_SHA"
        printf 'SOURCE_ENGINE_BYTES=%q\n' "$SOURCE_ENGINE_BYTES"
        printf 'SOURCE_FREE_BYTES=%q\n' "$SOURCE_FREE_BYTES"
        printf 'SOURCE_FREE_AFTER_RECLAIM_BYTES=%q\n' "$SOURCE_FREE_AFTER_RECLAIM_BYTES"
        printf 'PREFLIGHT_FREE_BYTES=%q\n' "$PREFLIGHT_FREE_BYTES"
        printf 'CACHE_BYTES=%q\n' "$RECOVERY_CACHE_BYTES"
        printf 'MAX_LOCAL_STORAGE_BYTES=%q\n' "$RECOVERY_MAX_LOCAL_STORAGE_BYTES"
        printf 'MIN_FREE_SPACE_BYTES=%q\n' "$RECOVERY_MIN_FREE_SPACE_BYTES"
        printf 'EXACT_SCAN_REQUESTED=%q\n' "$EXACT_SCAN_REQUESTED"
        if (( EXACT_SCAN_REQUESTED == 1 )); then
            printf 'VERIFICATION_SCOPE=%q\n' 'exact-stream-root-loss-recovery'
        else
            printf 'VERIFICATION_SCOPE=%q\n' 'sampled-remote-journal-recovery'
        fi
        printf 'BENCH_DLL=%q\n' "$SOURCE_BENCH_DLL"
        printf 'BENCH_SHA=%q\n' "$SOURCE_BENCH_SHA"
        printf 'BINARY_CLOSURE=%q\n' "$BINARY_CLOSURE"
        printf 'SOURCE_REPOSITORY=%q\n' "$SOURCE_REPOSITORY"
        printf 'SOURCE_COMMIT=%q\n' "$SOURCE_COMMIT"
        printf 'SOURCE_TREE_DIGEST=%q\n' "$SOURCE_TREE_DIGEST"
        printf 'SOURCE_WORKTREE_DIGEST=%q\n' "$SOURCE_WORKTREE_DIGEST"
        printf 'SOURCE_DIRTY=%q\n' "$SOURCE_SOURCE_DIRTY"
        printf 'FROZEN_MANIFEST_PATH=%q\n' "$FROZEN_MANIFEST_PATH"
        printf 'FROZEN_MANIFEST_SHA256=%q\n' "$FROZEN_MANIFEST_SHA256"
        printf 'DOTNET_BIN=%q\n' "$DOTNET_BIN"
        printf 'PREFIX=%q\n' "$SOURCE_PREFIX"
        printf 'RECORDS=%q\n' "$SOURCE_RECORDS"
        printf 'BATCH=%q\n' "$SOURCE_BATCH"
        printf 'PAYLOAD_BYTES=%q\n' "$SOURCE_PAYLOAD_BYTES"
        printf 'PAYLOAD_MODE=%q\n' "$SOURCE_PAYLOAD_MODE"
        printf 'SEED=%q\n' "$SOURCE_SEED"
        printf 'REGION=%q\n' "$SOURCE_REGION"
        printf 'ENDPOINT=%q\n' "$ENDPOINT"
        printf 'BUCKET=%q\n' "$BUCKET"
    } > "$RUN_DIR/launch.env"
    chmod 600 "$RUN_DIR/launch.env"
}

launch() {
    preflight >/dev/null
    write_launch_env
    systemd-run --user --no-block --collect --quiet --unit="$UNIT" \
        --property=MemoryMax=4294967296 \
        --property=MemorySwapMax=0 \
        --property=OOMPolicy=stop \
        --property=RuntimeMaxSec=12h \
        --property=WorkingDirectory="$BENCH_ROOT/bench" \
        --setenv=RECOVERY_OUTPUT="$RUN_DIR" \
        --setenv=RECOVERY_CREDENTIALS_FILE="$CREDENTIALS_FILE" \
        --setenv=LAUNCH_ENV_PARSER="$LAUNCH_ENV_PARSER" \
        /run/current-system/sw/bin/bash -lc '
            set -Eeuo pipefail
            source "$RECOVERY_CREDENTIALS_FILE"
            source "$LAUNCH_ENV_PARSER"
            load_launch_env_file "$RECOVERY_OUTPUT/launch.env" \
                OUTPUT RUN_DIR UNIT SOURCE_RUN_DIR SOURCE_RECEIPT SOURCE_RECEIPT_SHA \
                SOURCE_ENGINE_BYTES SOURCE_FREE_BYTES SOURCE_FREE_AFTER_RECLAIM_BYTES \
                PREFLIGHT_FREE_BYTES CACHE_BYTES MAX_LOCAL_STORAGE_BYTES \
                MIN_FREE_SPACE_BYTES EXACT_SCAN_REQUESTED VERIFICATION_SCOPE \
                BENCH_DLL BENCH_SHA BINARY_CLOSURE SOURCE_REPOSITORY \
                SOURCE_COMMIT SOURCE_TREE_DIGEST SOURCE_WORKTREE_DIGEST SOURCE_DIRTY \
                FROZEN_MANIFEST_PATH FROZEN_MANIFEST_SHA256 DOTNET_BIN PREFIX RECORDS \
                BATCH PAYLOAD_BYTES PAYLOAD_MODE SEED REGION ENDPOINT BUCKET
            export TERRABASE_S3_ENDPOINT="$ENDPOINT"
            export TERRABASE_S3_BUCKET="$BUCKET"
            export TERRABASE_FROZEN_SOURCE_PROJECT="$SOURCE_REPOSITORY/src/TerraBase/TerraBase.csproj"
            export TERRABASE_FROZEN_SOURCE_REPOSITORY="$SOURCE_REPOSITORY"
            export TERRABASE_FROZEN_SOURCE_COMMIT="$SOURCE_COMMIT"
            export TERRABASE_FROZEN_SOURCE_TREE_DIGEST="$SOURCE_TREE_DIGEST"
            export TERRABASE_FROZEN_SOURCE_WORKING_TREE_DIGEST="$SOURCE_WORKTREE_DIGEST"
            export TERRABASE_FROZEN_SOURCE_DIRTY="$SOURCE_DIRTY"
            export TERRABASE_FROZEN_MANIFEST_PATH="$FROZEN_MANIFEST_PATH"
            export TERRABASE_FROZEN_MANIFEST_SHA256="$FROZEN_MANIFEST_SHA256"
            export TERRABASE_FROZEN_BINARY_CLOSURE="$BINARY_CLOSURE"
            export TERRABASE_FROZEN_BENCHMARK_ASSEMBLY_SHA256="$BENCH_SHA"
            exec > "$RECOVERY_OUTPUT/console.log" 2>&1
            exact_scan_args=()
            if [[ "$EXACT_SCAN_REQUESTED" == 1 ]]; then
                exact_scan_args+=(--exact-scan)
            fi
            if nice -n 19 "$DOTNET_BIN" "$BENCH_DLL" \
                --workload tiered-segment \
                --recover-existing \
                "${exact_scan_args[@]}" \
                --source-receipt "$SOURCE_RECEIPT" \
                --source-receipt-sha256 "$SOURCE_RECEIPT_SHA" \
                --records "$RECORDS" \
                --batch "$BATCH" \
                --payload-bytes "$PAYLOAD_BYTES" \
                --payload-mode "$PAYLOAD_MODE" \
                --seed "$SEED" \
                --prefix "$PREFIX" \
                --require-isolated-cgroup \
                --max-local-storage-bytes "$MAX_LOCAL_STORAGE_BYTES" \
                --min-free-space-bytes "$MIN_FREE_SPACE_BYTES" \
                --cache-bytes "$CACHE_BYTES" \
                --resource-sample-ms 500 \
                --s3-endpoint "$ENDPOINT" \
                --s3-bucket "$BUCKET" \
                --s3-region "$REGION" \
                --output "$RECOVERY_OUTPUT"; then
                printf "exitCode=0\n" > "$RECOVERY_OUTPUT/benchmark-exit-status.tmp"
                mv -- "$RECOVERY_OUTPUT/benchmark-exit-status.tmp" "$RECOVERY_OUTPUT/benchmark-exit-status"
            else
                exit "$?"
            fi
        '
    printf 'launched=true\nrun_dir=%s\nunit=%s\n' "$RUN_DIR" "$UNIT"
}

verify_resource_sampler() {
    local receipt="$RUN_DIR/tiered-rustfs-recovery-receipt.json"
    local resource_samples="$RUN_DIR/resource-samples.jsonl"
    local resource_envelope="$RUN_DIR/resource-envelope.json"
    local samples_path max_local minimum_free recorded_peak latest_local latest_cache
    local minimum_observed sampler_error

    samples_path="$(jq -r '.ResourceSamplesPath // empty' "$receipt")"
    [[ "$samples_path" == "$resource_samples" ]] ||
        die "recovery receipt resource sampler path is not the run-owned resource-samples.jsonl"
    [[ -f "$resource_samples" && ! -L "$resource_samples" && -s "$resource_samples" ]] ||
        die "resource sampler receipt is missing, empty, or a symlink"
    [[ -f "$resource_envelope" && ! -L "$resource_envelope" && -s "$resource_envelope" ]] ||
        die "resource envelope is missing, empty, or a symlink"

    max_local="$(jq -r '.MaxLocalStorageBytes // empty' "$receipt")"
    minimum_free="$(jq -r '.MinimumFreeSpaceBytes // empty' "$receipt")"
    recorded_peak="$(jq -r '.PeakLocalStorageBytes // empty' "$receipt")"
    latest_local="$(jq -r '.LatestLocalStorageBytes // empty' "$receipt")"
    latest_cache="$(jq -r '.LatestCacheBytes // empty' "$receipt")"
    minimum_observed="$(jq -r '.MinimumObservedFreeSpaceBytes // empty' "$receipt")"
    sampler_error="$(jq -r '.ResourceSamplerError // empty' "$receipt")"
    [[ "$max_local" == "$RECOVERY_MAX_LOCAL_STORAGE_BYTES" ]] ||
        die "recovery receipt local-storage cap is not $RECOVERY_MAX_LOCAL_STORAGE_BYTES"
    [[ "$minimum_free" == "$RECOVERY_MIN_FREE_SPACE_BYTES" ]] ||
        die "recovery receipt free-space floor is not $RECOVERY_MIN_FREE_SPACE_BYTES"
    [[ "$recorded_peak" =~ ^[1-9][0-9]*$ && "$recorded_peak" -le "$max_local" ]] ||
        die "recovery receipt recorded peak local bytes exceed the local-storage cap or are missing"
    [[ "$latest_local" =~ ^[1-9][0-9]*$ && "$latest_local" -le "$max_local" ]] ||
        die "recovery receipt latest local bytes exceed the local-storage cap or are missing"
    [[ "$latest_cache" =~ ^[0-9]+$ && "$latest_cache" -le "$RECOVERY_CACHE_BYTES" ]] ||
        die "recovery receipt latest cache bytes exceed the cache cap or are missing"
    [[ "$minimum_observed" =~ ^[0-9]+$ && "$minimum_observed" -ge "$minimum_free" ]] ||
        die "recovery receipt observed free space fell below the configured floor"
    [[ -z "$sampler_error" ]] || die "recovery resource sampler reported an error"

    jq -s -e \
        --argjson max_local "$max_local" \
        --argjson minimum_free "$minimum_free" \
        --argjson recorded_peak "$recorded_peak" \
        --argjson latest_local "$latest_local" \
        --argjson latest_cache "$latest_cache" \
        --argjson cache_bytes "$RECOVERY_CACHE_BYTES" \
        --argjson minimum_observed "$minimum_observed" \
        '
        def nonnegative:
            if type != "number" then false else isfinite and . >= 0 end;
        def zero_events:
            if type != "string" then false
            else test("(^|\\n)oom 0(\\n|$)")
                 and test("(^|\\n)oom_kill 0(\\n|$)")
                 and test("(^|\\n)oom_group_kill 0(\\n|$)")
            end;
        def valid_cgroup:
            if type != "object" then false
            else .MemoryMax == "4294967296"
                 and .SwapMax == "0"
                 and .SwapCurrent == "0"
                 and (.MemoryEvents | zero_events)
            end;
        def valid_sample:
            if type != "object" then false
            else (.utc | type == "string")
                 and (.localStorageBytes | nonnegative)
                 and (.ssdCacheBytes | nonnegative)
                 and (.availableFreeSpaceBytes | nonnegative)
                 and (.workingSetBytes | nonnegative)
                 and (.peakRssBytes | nonnegative)
                 and (.cgroup | valid_cgroup)
            end;
        if length == 0 then error("resource sampler receipt has no samples")
        elif any(.[]; (valid_sample | not)) then error("resource sampler receipt has an invalid sample")
        elif any(.[]; .localStorageBytes > $max_local) then error("resource sampler local-storage cap was exceeded")
        elif any(.[]; .ssdCacheBytes > $cache_bytes) then error("resource sampler cache cap was exceeded")
        elif any(.[]; .availableFreeSpaceBytes < $minimum_free) then error("resource sampler free-space floor was exceeded")
        elif (map(.localStorageBytes) | max) != $recorded_peak then error("recorded peak local bytes do not match the sampler")
        elif (map(.localStorageBytes) | max) > $max_local then error("recorded peak local bytes exceed the local-storage cap")
        elif (map(.ssdCacheBytes) | max) > $cache_bytes then error("recorded cache bytes exceed the cache cap")
        elif (map(.availableFreeSpaceBytes) | min) < $minimum_free then error("recorded free-space samples fall below the floor")
        elif $minimum_observed < $minimum_free then error("recorded minimum free space falls below the floor")
        else {
            schema: "terrabase-rustfs-recovery-resource-v1",
            sampleCount: length,
            observedPeakLocalStorageBytes: (map(.localStorageBytes) | max),
            recordedPeakLocalStorageBytes: $recorded_peak,
            observedPeakCacheBytes: (map(.ssdCacheBytes) | max),
            cacheCapBytes: $cache_bytes,
            observedMinimumFreeSpaceBytes: (map(.availableFreeSpaceBytes) | min),
            recordedMinimumFreeSpaceBytes: $minimum_observed,
            minimumFreeSpaceBytes: $minimum_free,
            latestLocalStorageBytes: $latest_local,
            latestCacheBytes: $latest_cache,
            oomAndSwap: "zero"
        }
        end
        ' "$resource_samples" > "$RUN_DIR/resource-verification.json.tmp" || {
        rm -f -- "$RUN_DIR/resource-verification.json.tmp"
        die "resource sampler receipt verification failed"
    }
    mv -- "$RUN_DIR/resource-verification.json.tmp" "$RUN_DIR/resource-verification.json"

    jq -e \
        'type == "object"
         and .MemoryMax == "4294967296"
         and .SwapMax == "0"
         and .SwapCurrent == "0"
         and (.MemoryEvents | type == "string")
         and (.MemoryEvents | test("(^|\\n)oom 0(\\n|$)"))
         and (.MemoryEvents | test("(^|\\n)oom_kill 0(\\n|$)"))
         and (.MemoryEvents | test("(^|\\n)oom_group_kill 0(\\n|$)"))' \
        "$resource_envelope" > "$RUN_DIR/resource-envelope-verification.json.tmp" || {
        rm -f -- "$RUN_DIR/resource-envelope-verification.json.tmp"
        die "resource envelope verification failed"
    }
    mv -- "$RUN_DIR/resource-envelope-verification.json.tmp" "$RUN_DIR/resource-envelope-verification.json"
}

verify() {
    require_commands
    [[ -n "$RUN_DIR" && -d "$RUN_DIR" ]] || die "--run-dir is required"
    local requested_run_dir="$RUN_DIR"
    [[ -f "$RUN_DIR/launch.env" ]] || die "recovery launch.env is missing"
    load_launch_env_file "$RUN_DIR/launch.env" \
        OUTPUT RUN_DIR UNIT SOURCE_RUN_DIR SOURCE_RECEIPT SOURCE_RECEIPT_SHA \
        SOURCE_ENGINE_BYTES SOURCE_FREE_BYTES SOURCE_FREE_AFTER_RECLAIM_BYTES \
        PREFLIGHT_FREE_BYTES CACHE_BYTES MAX_LOCAL_STORAGE_BYTES \
        MIN_FREE_SPACE_BYTES EXACT_SCAN_REQUESTED VERIFICATION_SCOPE \
        BENCH_DLL BENCH_SHA BINARY_CLOSURE SOURCE_REPOSITORY \
        SOURCE_COMMIT SOURCE_TREE_DIGEST SOURCE_WORKTREE_DIGEST SOURCE_DIRTY \
        FROZEN_MANIFEST_PATH FROZEN_MANIFEST_SHA256 DOTNET_BIN PREFIX RECORDS \
        BATCH PAYLOAD_BYTES PAYLOAD_MODE SEED REGION ENDPOINT BUCKET \
        || die "recovery launch.env failed strict metadata validation"
    [[ "$RUN_DIR" == "$requested_run_dir" && "$OUTPUT" == "$requested_run_dir" ]] ||
        die "recovery launch.env output does not match --run-dir"
    RUN_DIR="$requested_run_dir"
    [[ "${CACHE_BYTES:-}" == "$RECOVERY_CACHE_BYTES" ]] || die "recovery launch cache cap is not $RECOVERY_CACHE_BYTES"
    [[ "${MAX_LOCAL_STORAGE_BYTES:-}" == "$RECOVERY_MAX_LOCAL_STORAGE_BYTES" ]] || die "recovery launch local-storage cap is not $RECOVERY_MAX_LOCAL_STORAGE_BYTES"
    [[ "${MIN_FREE_SPACE_BYTES:-}" == "$RECOVERY_MIN_FREE_SPACE_BYTES" ]] || die "recovery launch free-space floor is not $RECOVERY_MIN_FREE_SPACE_BYTES"
    [[ "$(systemctl --user show "$UNIT" -p ActiveState --value 2>/dev/null || true)" != active ]] || die "recovery unit is still active"
    [[ -f "$RUN_DIR/benchmark-exit-status" && "$(cat "$RUN_DIR/benchmark-exit-status")" == exitCode=0 ]] || die "recovery process did not exit successfully"
    [[ -s "$RUN_DIR/tiered-rustfs-recovery-receipt.json" ]] || die "recovery receipt is missing"
    [[ -s "$RUN_DIR/tiered-rustfs-recovery-summary.md" ]] || die "recovery summary is missing"
    [[ ! -d "$SOURCE_RUN_DIR/engine" ]] || die "source engine root still exists after recovery"
    [[ -s "$RUN_DIR/engine/wal" ]] || die "recovered WAL is missing or empty"
    [[ "$(sha256sum "$SOURCE_RECEIPT" | awk '{ print $1 }')" == "$SOURCE_RECEIPT_SHA" ]] || die "source receipt changed"

    local source_ack_records source_frontier
    source_ack_records="$(jq -r '.RemoteAck.AcknowledgedRecords // empty' "$SOURCE_RECEIPT")"
    source_frontier="$(jq -r '.RemoteValidatedFrontier // empty' "$SOURCE_RECEIPT")"
    [[ "$source_ack_records" =~ ^[1-9][0-9]*$ && "$source_frontier" =~ ^[1-9][0-9]*$ ]] || die "source receipt lacks remote acknowledgement frontier"
    (( source_ack_records >= RECORDS )) || die "source receipt remote acknowledgement is below the target record count"
    [[ "$source_frontier" == "$source_ack_records" ]] || die "source receipt acknowledgement and validated frontier differ"

    verify_resource_sampler

    local exact_scan_requested="${EXACT_SCAN_REQUESTED:-0}"
    local verification_scope
    if [[ "$exact_scan_requested" == 1 ]]; then
        verification_scope='exact-stream-root-loss-recovery'
    else
        verification_scope='sampled-remote-journal-recovery'
    fi
    jq -e \
        --argjson records "$RECORDS" \
        --argjson source_ack_records "$source_ack_records" \
        --argjson source_frontier "$source_frontier" \
        --arg source_repository "${SOURCE_REPOSITORY:-}" \
        --arg source_commit "${SOURCE_COMMIT:-}" \
        --arg source_tree "${SOURCE_TREE_DIGEST:-}" \
        --arg source_worktree "${SOURCE_WORKTREE_DIGEST:-}" \
        --argjson source_dirty "${SOURCE_DIRTY:-false}" \
        --arg frozen_manifest "${FROZEN_MANIFEST_PATH:-}" \
        --arg frozen_manifest_sha "${FROZEN_MANIFEST_SHA256:-}" \
        --arg frozen_closure "${BINARY_CLOSURE:-}" \
        --arg frozen_sha "${BENCH_SHA:-}" \
        --arg verification_scope "$verification_scope" \
        --argjson exact_scan_requested "$exact_scan_requested" \
        --arg resource_samples_path "$RUN_DIR/resource-samples.jsonl" \
        --argjson max_local_storage_bytes "$RECOVERY_MAX_LOCAL_STORAGE_BYTES" \
        --argjson minimum_free_space_bytes "$RECOVERY_MIN_FREE_SPACE_BYTES" \
        --argjson cache_bytes "$RECOVERY_CACHE_BYTES" \
        '.Status == "complete"
         and .Mode == "recover-existing"
         and .VerificationScope == $verification_scope
         and .ExpectedRecords == $records
         and .SourceRootDeleted == true
         and .SourceReceiptUnchanged == true
         and (if $source_repository == "" then true else
              .Subject.Project == ($source_repository + "/src/TerraBase/TerraBase.csproj")
              and .Subject.Repository == $source_repository
              and .Subject.Commit == $source_commit
              and .Subject.TreeDigest == $source_tree
              and .Subject.WorkingTreeDigest == $source_worktree
              and .Subject.Dirty == $source_dirty
              and .Subject.Frozen.Project == ($source_repository + "/src/TerraBase/TerraBase.csproj")
              and .Subject.Frozen.Repository == $source_repository
              and .Subject.Frozen.Commit == $source_commit
              and .Subject.Frozen.TreeDigest == $source_tree
              and .Subject.Frozen.WorkingTreeDigest == $source_worktree
              and .Subject.Frozen.Dirty == $source_dirty
              and .Subject.Frozen.ManifestPath == $frozen_manifest
              and .Subject.Frozen.ManifestSha256 == $frozen_manifest_sha
              and .Subject.Frozen.BinaryClosure == $frozen_closure
              and .Subject.Frozen.BenchmarkAssemblySha256 == $frozen_sha
              and .Subject.Live.Project == ($source_repository + "/src/TerraBase/TerraBase.csproj")
              end)
         and .RecoveredWalBytes > 0
         and .SourceRemoteAckRecords == $source_ack_records
         and .SourceInternalAuthorityRecords == ($source_ack_records - $records)
         and .RecoveredFrontier == $source_frontier
         and .RemoteValidatedFrontier == $source_frontier
         and .RemoteFrontierUnchanged == true
         and .SampleCount > 0
         and .SampleCount <= 4096
         and .SampleReadsByPhase["first-reopen"] == .SampleCount
         and .SampleReadsByPhase["second-reopen"] == .SampleCount
         and (if $exact_scan_requested == 1
              then .ExactScan == "complete" and .ExactScanCount == $records
              else .ExactScan == "skipped"
              end)
         and has("ResourceSamplesPath")
         and .ResourceSamplesPath == $resource_samples_path
         and has("PeakLocalStorageBytes")
         and .PeakLocalStorageBytes > 0
         and .PeakLocalStorageBytes <= $max_local_storage_bytes
         and has("LatestLocalStorageBytes")
         and .LatestLocalStorageBytes > 0
         and .LatestLocalStorageBytes <= $max_local_storage_bytes
         and has("LatestCacheBytes")
         and .LatestCacheBytes >= 0
         and .LatestCacheBytes <= $cache_bytes
         and has("MaxLocalStorageBytes")
         and .MaxLocalStorageBytes == $max_local_storage_bytes
         and has("MinimumFreeSpaceBytes")
         and .MinimumFreeSpaceBytes == $minimum_free_space_bytes
         and has("MinimumObservedFreeSpaceBytes")
         and .MinimumObservedFreeSpaceBytes >= $minimum_free_space_bytes
         and has("ResourceSamplerError")
         and .ResourceSamplerError == null
         and .FinalCgroup.MemoryMax == "4294967296"
         and .FinalCgroup.SwapMax == "0"
         and .FinalCgroup.SwapCurrent == "0"
         and (.FinalCgroup.MemoryEvents | test("(^|\\n)oom 0(\\n|$)"))
         and (.FinalCgroup.MemoryEvents | test("(^|\\n)oom_kill 0(\\n|$)"))
         and (.FinalCgroup.MemoryEvents | test("(^|\\n)oom_group_kill 0(\\n|$)"))' \
        "$RUN_DIR/tiered-rustfs-recovery-receipt.json" > "$RUN_DIR/receipt-verification.json" || die "recovery receipt verification failed"
    sha256sum "$RUN_DIR/tiered-rustfs-recovery-receipt.json" \
        "$RUN_DIR/tiered-rustfs-recovery-summary.md" \
        "$RUN_DIR/resource-verification.json" \
        "$RUN_DIR/resource-envelope-verification.json" \
        > "$RUN_DIR/verified-sha256sums.txt"
    printf 'verification=ok\nrun_dir=%s\n' "$RUN_DIR"
}

parse_args() {
    (($# > 0)) && case "$1" in preflight|launch|verify) MODE="$1"; shift ;; esac
    while (($# > 0)); do
        case "$1" in
            --source-run-dir) (($# >= 2)) || die "--source-run-dir requires a path"; SOURCE_RUN_DIR="$2"; shift 2 ;;
            --run-dir) (($# >= 2)) || die "--run-dir requires a path"; RUN_DIR="$2"; shift 2 ;;
            --manifest) (($# >= 2)) || die "--manifest requires a path"; MANIFEST="$2"; MANIFEST_EXPLICIT=1; shift 2 ;;
            --run-label) (($# >= 2)) || die "--run-label requires a label"; RUN_LABEL="$2"; shift 2 ;;
            --dotnet) (($# >= 2)) || die "--dotnet requires a path"; DOTNET_BIN="$2"; DOTNET_EXPLICIT=1; shift 2 ;;
            --credentials-file) (($# >= 2)) || die "--credentials-file requires a path"; CREDENTIALS_FILE="$2"; shift 2 ;;
            --endpoint) (($# >= 2)) || die "--endpoint requires a URL"; ENDPOINT="$2"; shift 2 ;;
            --bucket) (($# >= 2)) || die "--bucket requires a name"; BUCKET="$2"; shift 2 ;;
            --exact-scan) EXACT_SCAN_REQUESTED=1; shift ;;
            --help|-h) usage; exit 0 ;;
            *) die "unknown argument: $1 (use --help)" ;;
        esac
    done
}

main() {
    parse_args "$@"
    case "$MODE" in
        preflight) preflight ;;
        launch) launch ;;
        verify) verify ;;
        *) die "unsupported mode: $MODE" ;;
    esac
}

main "$@"
