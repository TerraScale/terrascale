#!/usr/bin/env bash
# E-13 local bench subject: one served TerraBase member for terrabase-only
# benchmark runs on a development host.
#
# Everything is loopback, throwaway, and never shipped: dev TLS, a dev
# bootstrap API key, one member under the standard 2 OCPU / 12 GiB launch
# envelope so the bench drivers' resource evidence is real. The artifact
# digests it prints are the sha256 of the exact release binary it serves —
# the immutable identity of the measured runtime, never a placeholder.
#
#   bench/scripts/local-member.sh up      # build release, boot fenced member
#   bench/scripts/local-member.sh env     # print eval-able exports for families
#   bench/scripts/local-member.sh down    # stop the member (state is kept)
#   LOCAL_MEMBER_FRESH=1 ... up           # wipe state first
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
MEMBER_DIR="$REPO_ROOT/bench/.member"
API_PORT="${LOCAL_MEMBER_API_PORT:-7211}"
TBEP_PORT="${LOCAL_MEMBER_TBEP_PORT:-8531}"
OBS_PORT="${LOCAL_MEMBER_OBS_PORT:-9571}"
BIN="$REPO_ROOT/target/release/terrabase-server"
REGION="${LOCAL_MEMBER_REGION:-GRU}"

# shellcheck disable=SC1091
source "$SCRIPT_DIR/resource-envelope.sh"

log() { printf 'local-member: %s\n' "$1" >&2; }
die() { printf 'local-member: %s\n' "$1" >&2; exit 1; }

tls_has_padding() {
  grep -q '=' "$MEMBER_DIR/tls/server.crt" "$MEMBER_DIR/tls/server.key" "$MEMBER_DIR/tls/ca.crt" 2>/dev/null
}

# The member's PEM gate rejects base64 lines that mix '=' padding with
# content (see scripts/stack.sh), so mint until padding-free.
ensure_tls() {
  if [[ -f "$MEMBER_DIR/tls/server.crt" && -f "$MEMBER_DIR/tls/server.key" \
    && -f "$MEMBER_DIR/tls/ca.crt" ]] && ! tls_has_padding; then
    return 0
  fi
  mkdir -p "$MEMBER_DIR/tls"
  umask 077
  local attempt=0
  while ((attempt < 100)); do
    attempt=$((attempt + 1))
    openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:P-256 \
      -keyout "$MEMBER_DIR/tls/ca.key" -out "$MEMBER_DIR/tls/ca.crt" \
      -days 3 -nodes -subj "/CN=terrabase-bench-ca" 2>/dev/null
    openssl req -newkey ec -pkeyopt ec_paramgen_curve:P-256 \
      -keyout "$MEMBER_DIR/tls/server.key" -out "$MEMBER_DIR/tls/server.csr" \
      -nodes -subj "/CN=127.0.0.1" 2>/dev/null
    printf 'subjectAltName=IP:127.0.0.1,DNS:localhost\n' >"$MEMBER_DIR/tls/san.ext"
    openssl x509 -req -in "$MEMBER_DIR/tls/server.csr" \
      -CA "$MEMBER_DIR/tls/ca.crt" -CAkey "$MEMBER_DIR/tls/ca.key" -CAcreateserial \
      -out "$MEMBER_DIR/tls/server.crt" -days 3 -extfile "$MEMBER_DIR/tls/san.ext" 2>/dev/null
    rm -f "$MEMBER_DIR/tls/server.csr"
    tls_has_padding || { log "dev TLS minted after $attempt attempt(s)"; return 0; }
  done
  die "could not mint padding-free dev certificates in 100 attempts"
}

ensure_key() {
  if [[ -f "$MEMBER_DIR/bootstrap.key" ]]; then
    return 0
  fi
  umask 077
  printf 'tskey_bench_%s' "$(openssl rand -hex 24)" >"$MEMBER_DIR/bootstrap.key"
  log "minted dev bootstrap API key"
}

write_config() {
  umask 077
  {
    printf '# E-13 local bench subject. Generated by local-member.sh; do not hand-edit.\n'
    printf '# Development only: throwaway certs, bootstrap key, loopback listeners.\n\n'
    printf '[engine]\n'
    printf 'location = "%s/engine"\n' "$MEMBER_DIR"
    printf 'tenant = "terrabase-local"\nproject = "local"\ndatabase = "local"\n'
    printf 'instance_id = 1\nregion = "%s"\n\n' "$REGION"
    printf '[tbep]\nlisten = "127.0.0.1:%s"\n' "$TBEP_PORT"
    printf 'server_certificate = "%s/tls/server.crt"\n' "$MEMBER_DIR"
    printf 'server_private_key = "%s/tls/server.key"\n' "$MEMBER_DIR"
    printf 'client_ca = "%s/tls/ca.crt"\n' "$MEMBER_DIR"
    printf 'member_principals = ["spiffe://local/stack-member"]\n'
    printf 'max_message_bytes = 16777216\nmax_inflight = 128\n'
    printf 'request_timeout_millis = 30000\ntls_handshake_timeout_millis = 5000\nshutdown_grace_millis = 30000\n\n'
    printf '[observability]\nlisten = "127.0.0.1:%s"\n\n' "$OBS_PORT"
    printf '[public_api]\nlisten = "127.0.0.1:%s"\n' "$API_PORT"
    printf 'data_root = "%s/data"\n' "$MEMBER_DIR"
    printf 'bootstrap_key_file = "%s/bootstrap.key"\n' "$MEMBER_DIR"
    printf 'regions = ["%s"]\n' "$REGION"
    # No [replication] section: the standalone one-member shape. An explicit
    # empty peers list is a configuration error by design.
  } >"$MEMBER_DIR/member.toml"
}

member_pid() { cat "$MEMBER_DIR/member.pid" 2>/dev/null || true; }

cmd_down() {
  local pid
  pid="$(member_pid)"
  if [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null; then
    log "stopping member (pid $pid)"
    kill "$pid" 2>/dev/null || true
    local waited=0
    while kill -0 "$pid" 2>/dev/null && ((waited < 10)); do
      sleep 1
      waited=$((waited + 1))
    done
    kill -9 "$pid" 2>/dev/null || true
  fi
  rm -f "$MEMBER_DIR/member.pid"
  log "member stopped (state kept under $MEMBER_DIR)"
}

healthy() {
  curl -sf --max-time 2 -H "Authorization: Bearer $(cat "$MEMBER_DIR/bootstrap.key")" \
    "http://127.0.0.1:$API_PORT/api/v1/health" 2>/dev/null
}

cmd_up() {
  if [[ "$(member_pid)" ]] && healthy >/dev/null 2>&1; then
    log "member already up (pid $(member_pid))"
    return 0
  fi
  cmd_down || true
  if [[ "${LOCAL_MEMBER_FRESH:-0}" == 1 ]]; then
    log "LOCAL_MEMBER_FRESH=1: wiping $MEMBER_DIR"
    rm -rf "$MEMBER_DIR"
  fi
  mkdir -p "$MEMBER_DIR/engine" "$MEMBER_DIR/data" "$MEMBER_DIR/logs"
  ensure_tls
  ensure_key
  write_config
  # Always run the incremental build: a stale pre-built binary silently
  # serves an older contract than the checkout (cargo is a no-op when fresh).
  log "ensuring release terrabase-server is current"
  (cd "$REPO_ROOT" && nice -n 19 cargo build --release --locked -p terrabase-server)
  envelope_require
  local cpus
  cpus="$(envelope_cpu_set)"
  log "starting $REGION member: api 127.0.0.1:$API_PORT under $TERRABASE_BENCH_ENVELOPE_SPEC on cpus $cpus"
  # The measured subject and the bench drivers share one fenced scope, which
  # is exactly the evidence shape the drivers record.
  systemd-run --user --scope --quiet \
    -p MemoryMax="$TERRABASE_BENCH_ENVELOPE_MEMORY" \
    -p CPUQuota=200% -p AllowedCPUs="$cpus" -p TasksMax=4096 \
    -- taskset -c "$cpus" nice -n 19 \
    setsid "$BIN" --config "$MEMBER_DIR/member.toml" \
    >>"$MEMBER_DIR/logs/member.log" 2>&1 &
  local supervise=$!
  local deadline=$((SECONDS + 90))
  while ((SECONDS < deadline)); do
    if healthy >/dev/null 2>&1; then
      break
    fi
    if ! kill -0 "$supervise" 2>/dev/null; then
      tail -n 20 "$MEMBER_DIR/logs/member.log" >&2 || true
      die "member exited before becoming healthy"
    fi
    sleep 1
  done
  healthy >/dev/null 2>&1 || { tail -n 20 "$MEMBER_DIR/logs/member.log" >&2; die "member not healthy in 90 s"; }
  # The member is its own session leader; the pid inside the scope is found
  # from the server process itself, not the systemd-run wrapper.
  local pid
  pid="$(pgrep -f "terrabase-server --config $MEMBER_DIR/member.toml" | head -1 || true)"
  [[ -n "$pid" ]] || die "cannot find member pid"
  printf '%s\n' "$pid" >"$MEMBER_DIR/member.pid"
  envelope_subject_evidence "terrabase-member" "$pid" "$MEMBER_DIR/resource-evidence.txt"
  log "member up (pid $pid); evidence at $MEMBER_DIR/resource-evidence.txt"
}

cmd_env() {
  [[ -n "$(member_pid)" ]] || die "member is not up; run local-member.sh up"
  local digest
  digest="$(sha256sum "$BIN" | awk '{print $1}')"
  cat <<ENV
export TERRABASE_BENCH_MEMBER_API="http://127.0.0.1:$API_PORT"
export TERRABASE_BENCH_MEMBER_HEALTH="http://127.0.0.1:$API_PORT/api/v1/health"
export TERRABASE_BENCH_MEMBER_AUTH="Authorization: Bearer $(cat "$MEMBER_DIR/bootstrap.key")"
export TERRABASE_BENCH_MEMBER_KEY="$(cat "$MEMBER_DIR/bootstrap.key")"
export TERRABASE_BENCH_MEMBER_VERSION="$(healthy | python3 -c 'import json,sys; print(json.load(sys.stdin)["version"])')"
export TERRABASE_BENCH_MEMBER_ARTIFACT_SHA256="$digest"
export TERRABASE_BENCH_MEMBER_RESOURCE_EVIDENCE="$MEMBER_DIR/resource-evidence.txt"
export TERRABASE_BENCH_MEMBER_PID="$(member_pid)"
ENV
}

case "${1:-up}" in
  up) cmd_up ;;
  down) cmd_down ;;
  env) cmd_env ;;
  -h|--help) sed -n '2,14p' "$0" ;;
  *) die "unknown command: $1 (up|down|env)" ;;
esac
