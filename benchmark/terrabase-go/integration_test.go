// TestProductionHarnessInterop drives the real engine: the Rust
// tbep-production-harness binary behind gRPC TLS, built from this
// repository. It is the live interop gate of the Go client.
//
// Enable with TERRABASE_HARNESS:
//
//	TERRABASE_HARNESS=1 go test -tags integration ./...
//
// The value may name the harness binary directly (an absolute or
// working-directory-relative path); any other non-empty value builds
// it first with
//
//	cargo build -p terrabase-tbep --bin tbep-production-harness --release
//
// from the repository root, which reuses the cargo target cache.
//
// Limits of this lane, stated plainly:
//
//   - Loopback only: the harness binds 127.0.0.1:0; nothing crosses a
//     network, so it never exercises real latency, TLS termination, or
//     intermediaries.
//   - Dev lane: the certificate hierarchy is thrownaway ECDSA material
//     generated by this test, not operator-provisioned; the storage
//     directory is a temp dir destroyed with the test, so no
//     durability-across-restart claim is made.
//   - One standalone instance: no cluster, replication observation, or
//     failover behavior is exercised. The harness's engine host does
//     not serve backbone delivery (the sync-delivery host beside it
//     does), so the subscription stream itself is covered by the
//     offline fake-server suite; this lane only checks its refusal
//     decodes into the typed error model. The sync, family, schema,
//     and tier seams are likewise fake-suite territory.
func TestProductionHarnessInterop(t *testing.T) {
	harnessSetting := os.Getenv("TERRABASE_HARNESS")
	if harnessSetting == "" {
		t.Skip("set TERRABASE_HARNESS=1 (or the harness binary path) to run the live interop lane")
	}
	binary, err := harnessBinary(t, harnessSetting)
	if err != nil {
		t.Fatalf("the harness binary could not be resolved: %v", err)
	}

	// The qualification material the harness expects: a server chain,
	// its key, and the client root, all PEM on disk.
	pki := newTestPKI(t)
	directory := t.TempDir()
	write := func(name string, payload []byte) string {
		t.Helper()
		path := filepath.Join(directory, name)
		if err := os.WriteFile(path, payload, 0o600); err != nil {
			t.Fatalf("%s could not be written: %v", name, err)
		}
		return path
	}
	serverCert := write("server-cert-chain.pem", pki.serverPEM)
	serverKey := write("server-key.pem", pki.serverKey)
	clientRoot := write("client-root.pem", pki.caPEM)
	storage := t.TempDir()

	command := exec.Command(binary, serverCert, serverKey, clientRoot, storage,
		testGatewayPrincipal, "tenant-go", "project-go", "database-go")
	stdin, err := command.StdinPipe()
	if err != nil {
		t.Fatalf("the harness stdin could not be piped: %v", err)
	}
	stdout, err := command.StdoutPipe()
	if err != nil {
		t.Fatalf("the harness stdout could not be piped: %v", err)
	}
	command.Stderr = os.Stderr
	if err := command.Start(); err != nil {
		t.Fatalf("the harness could not start: %v", err)
	}
	defer func() {
		_, _ = stdin.Write([]byte("shutdown\n"))
		_ = command.Wait()
	}()

	// The startup protocol: one line, "TBEP_PRODUCTION_LISTENER_READY
	// <port>", on stdout once the listener is bound.
	announce := make(chan string, 1)
	go func() {
		scanner := bufio.NewScanner(stdout)
		for scanner.Scan() {
			line := scanner.Text()
			if strings.HasPrefix(line, "TBEP_PRODUCTION_LISTENER_READY ") {
				announce <- strings.TrimSpace(strings.TrimPrefix(line, "TBEP_PRODUCTION_LISTENER_READY "))
				return
			}
		}
		announce <- ""
	}()
	var port string
	select {
	case port = <-announce:
		if port == "" {
			t.Fatal("the harness exited without announcing its listener")
		}
	case <-time.After(30 * time.Second):
		t.Fatal("the harness did not announce its listener within 30s")
	}
	roots := x509.NewCertPool()
	if !roots.AppendCertsFromPEM(pki.caPEM) {
		t.Fatal("the test CA could not be loaded")
	}
	legacyTLS := &tls.Config{
		RootCAs: roots, Certificates: []tls.Certificate{mustTLSCertificate(t, pki.clientPEM, pki.clientKey)},
		ServerName: "localhost", MinVersion: tls.VersionTLS12, MaxVersion: tls.VersionTLS12,
	}
	legacy, err := tls.Dial("tcp", "127.0.0.1:"+port, legacyTLS)
	if err == nil {
		_ = legacy.Close()
		t.Fatal("the production listener accepted a TLS 1.2 handshake")
	}
	// Hold one accepted TCP connection before sending any TLS bytes. A
	// serialized accept/handshake loop would make the valid client below wait
	// for the full five-second handshake deadline. The bounded concurrent
	// accept path must continue admitting it promptly, and the later shutdown
	// must cancel this pending handshake within the configured drain bound.
	slow, err := net.DialTimeout("tcp", "127.0.0.1:"+port, time.Second)
	if err != nil {
		t.Fatalf("the slow-handshake connection could not be opened: %v", err)
	}
	defer slow.Close()

	client, err := Dial("127.0.0.1:"+port,
		WithRootCerts(pki.caPEM),
		WithClientCert(pki.clientPEM, pki.clientKey),
	)
	if err != nil {
		t.Fatalf("the engine could not be dialed: %v", err)
	}
	defer client.Close()
	bindCtx, cancelBind := context.WithTimeout(context.Background(), 2*time.Second)

	scope := BindingScope{
		Principal: testGatewayPrincipal,
		Tenant:    "tenant-go",
		Project:   "project-go",
		Database:  "database-go",
	}
	binding, err := client.Bind(bindCtx, scope)
	cancelBind()
	if err != nil {
		t.Fatalf("the channel bind against the real engine failed: %v", err)
	}
	if binding.Scope != scope || binding.ServingInstance == 0 {
		t.Fatalf("the bind answer is wrong: %+v", binding)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()

	body := map[string]Value{
		"title": "Designing Data-Intensive Applications",
		"pages": 616,
		"tags":  []Value{"distributed", "storage"},
	}
	_, err = client.DocumentWrite(ctx,
		DocumentPut{Collection: "books", ID: "unadmitted", Body: body},
		ExpectAbsent(), AckLocalSynced, "go-integration-write-unadmitted")
	if !errors.Is(err, ErrUsageUnavailable) {
		t.Fatalf("an unadmitted production write must be refused with usage_unavailable, got %v", err)
	}
	if _, found, err := client.DocumentRead(ctx, "books", "unadmitted", ReadLevelGlobalQuorum); err != nil || found {
		t.Fatalf("the refused unadmitted write created data: found=%v err=%v", found, err)
	}
	outcome, err := client.DocumentWrite(ctx,
		DocumentPut{Collection: "books", ID: "ddia", Body: body},
		ExpectAbsent(), AckLocalSynced, "go-integration-write-1",
		WithUsageAdmission(UsageAdmissionContext{
			Project:          "project-go",
			Database:         "database-go",
			Partition:        "partition-go",
			OriginRegion:     UsageRegionGRU,
			RequestID:        "go-integration-write-1",
			AcceptedAtMillis: 1_788_091_200_000,
			MeterVersion:     1,
			IntegerUnits:     "1",
		}))
	if err != nil {
		t.Fatalf("the write against the real engine failed: %v", err)
	}
	receipt, committed := outcome.Committed()
	if !committed {
		t.Fatalf("the write against the real engine must commit, got %+v", outcome)
	}
	if receipt.Sequence == 0 || receipt.Version != 1 || receipt.OperationID != "go-integration-write-1" {
		t.Fatalf("the write receipt is wrong: %+v", receipt)
	}

	read, found, err := client.DocumentRead(ctx, "books", "ddia", ReadLevelGlobalQuorum)
	if err != nil || !found {
		t.Fatalf("the read-back failed: found=%v err=%v", found, err)
	}
	round, ok := read.Body.(map[string]Value)
	if !ok {
		t.Fatalf("the read-back body must be a map, got %T", read.Body)
	}
	if round["title"] != body["title"] || round["pages"] != int64(616) {
		t.Fatalf("the read-back body is wrong: %+v", round)
	}
	if tags, ok := round["tags"].([]Value); !ok || len(tags) != 2 {
		t.Fatalf("the read-back list is wrong: %#v", round["tags"])
	}

	result, err := client.QueryExecute(ctx, 1, "from books", 10, ReadLevelDefault)
	if err != nil {
		t.Fatalf("the query against the real engine failed: %v", err)
	}
	if result.Count < 1 || len(result.Documents) < 1 || result.Position == 0 {
		t.Fatalf("the query answer is wrong: %+v", result)
	}
	if result.Documents[0].ID != "ddia" {
		t.Fatalf("the query returned the wrong document: %+v", result.Documents[0])
	}

	// The admitted production mutation must mint one durable accounting fact.
	usage, err := client.UsageExport(ctx, UsageServiceExportRequest{PageSize: 1})
	if err != nil {
		t.Fatalf("the live usage export failed: %v", err)
	}
	if usage.SnapshotSequence == 0 || len(usage.Facts) != 1 || len(usage.Continuation) != 0 {
		t.Fatalf("the live usage page is wrong: %+v", usage)
	}
	fact := usage.Facts[0]
	if fact.FactID != receipt.OperationID || fact.Sequence != receipt.Sequence ||
		fact.Tenant != "tenant-go" || fact.Project != "project-go" || fact.Database != "database-go" ||
		fact.Partition != "partition-go" || fact.Region != UsageRegionGRU || fact.IntegerDelta != "1" ||
		fact.MeasurementStartMillis != 1_788_091_200_000 {
		t.Fatalf("the live usage fact is wrong: %+v", fact)
	}

	// The harness's durable engine host does not serve backbone
	// delivery — the sync-delivery host beside it does — so the stream
	// opens and its first frame is refused with the closed
	// operation_refused code. That refusal is a live check of the
	// typed error model: the code and detail must decode from the
	// real engine's status details.
	subscription, err := client.Subscribe(ctx, 1, []string{"books"}, FromLive())
	if err != nil {
		t.Fatalf("the subscription stream could not open: %v", err)
	}
	_, streamErr := subscription.Recv()
	var refusal *Error
	if !errors.As(streamErr, &refusal) {
		t.Fatalf("the subscription refusal must decode into the typed error, got %v", streamErr)
	}
	if refusal.Code != CodeOperationRefused || refusal.Detail == "" {
		t.Fatalf("the subscription refusal must carry its engine code and detail, got %+v", refusal)
	}
	if !errors.Is(streamErr, ErrOperationRefused) {
		t.Fatalf("the subscription refusal must answer ErrOperationRefused, got %v", streamErr)
	}
	if err := subscription.Close(); err != nil {
		t.Fatalf("the subscription close failed: %v", err)
	}

	// The shutdown protocol: "shutdown" on stdin, then a clean exit.
	if _, err := stdin.Write([]byte("shutdown\n")); err != nil {
		t.Fatalf("the shutdown command could not be sent: %v", err)
	}
	finished := make(chan error, 1)
	go func() { finished <- command.Wait() }()
	select {
	case waitError := <-finished:
		if waitError != nil {
			t.Fatalf("the harness did not exit cleanly: %v", waitError)
		}
	case <-time.After(15 * time.Second):
		t.Fatal("the harness did not exit within 15s of the shutdown command")
	}
}

func mustTLSCertificate(t *testing.T, certPEM, keyPEM []byte) tls.Certificate {
	t.Helper()
	pair, err := tls.X509KeyPair(certPEM, keyPEM)
	if err != nil {
		t.Fatalf("the test client certificate could not be loaded: %v", err)
	}
	return pair
}

// harnessBinary resolves the harness executable, building it with
// cargo when the environment does not name one.
func harnessBinary(t *testing.T, setting string) (string, error) {
	t.Helper()
	if setting != "1" && setting != "auto" {
		if info, err := os.Stat(setting); err == nil && !info.IsDir() && info.Mode()&0o111 != 0 {
			return setting, nil
		}
		return "", fmt.Errorf("TERRABASE_HARNESS=%q is neither 1, auto, nor an executable", setting)
	}
	_, thisFile, _, ok := runtime.Caller(0)
	if !ok {
		return "", errors.New("the repository root could not be derived")
	}
	root := filepath.Clean(filepath.Join(filepath.Dir(thisFile), ".."))
	binary := filepath.Join(root, "target", "release", "tbep-production-harness")
	if info, err := os.Stat(binary); err == nil && info.Mode()&0o111 != 0 {
		return binary, nil
	}
	t.Logf("building the harness: cargo build -p terrabase-tbep --bin tbep-production-harness --release (first build is slow)")
	build := exec.Command("cargo", "build", "-p", "terrabase-tbep", "--bin", "tbep-production-harness", "--release")
	build.Dir = root
	build.Stdout = os.Stdout
	build.Stderr = os.Stderr
	if err := build.Run(); err != nil {
		return "", fmt.Errorf("the cargo build failed: %w", err)
	}
	return binary, nil
}
