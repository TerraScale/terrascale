// Command normalize-generated-protoc-version canonicalizes the non-semantic
// protoc version line in the three checked-in TBEP Go bindings.
package main

import (
	"bytes"
	"crypto/rand"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"syscall"
)

const canonicalVersion = "v7.34.1"

type bindingSpec struct {
	name      string
	generated []byte
	unknown   []byte
	source    []byte
	grpc      bool
}

var specs = []bindingSpec{
	{"engine.pb.go", []byte("// Code generated by protoc-gen-go. DO NOT EDIT."), []byte("// \tprotoc        (unknown)"), []byte("// source: terrabase/v1/engine.proto"), false},
	{"engine_grpc.pb.go", []byte("// Code generated by protoc-gen-go-grpc. DO NOT EDIT."), []byte("// - protoc             (unknown)"), []byte("// source: terrabase/v1/engine.proto"), true},
	{"family.pb.go", []byte("// Code generated by protoc-gen-go. DO NOT EDIT."), []byte("// \tprotoc        (unknown)"), []byte("// source: terrabase/v1/family.proto"), false},
}

func fail(format string, args ...any) error { return fmt.Errorf(format, args...) }

func openDirectoryChain(path string) (int, error) {
	if !filepath.IsAbs(path) {
		return -1, fail("binding root must be absolute")
	}
	components := []string{}
	clean := filepath.Clean(path)
	remainder := clean[len(string(filepath.Separator)):]
	for len(remainder) > 0 {
		part := remainder
		if slash := stringsIndexByte(remainder, '/'); slash >= 0 {
			part, remainder = remainder[:slash], remainder[slash+1:]
		} else {
			remainder = ""
		}
		if part != "" {
			components = append(components, part)
		}
	}
	fd, err := syscall.Open("/", syscall.O_RDONLY|syscall.O_DIRECTORY|syscall.O_NOFOLLOW, 0)
	if err != nil {
		return -1, err
	}
	for _, component := range components {
		next, openErr := syscall.Openat(fd, component, syscall.O_RDONLY|syscall.O_DIRECTORY|syscall.O_NOFOLLOW, 0)
		if openErr != nil {
			syscall.Close(fd)
			return -1, openErr
		}
		syscall.Close(fd)
		fd = next
	}
	return fd, nil
}

func stringsIndexByte(value string, needle byte) int {
	for index := 0; index < len(value); index++ {
		if value[index] == needle {
			return index
		}
	}
	return -1
}

func readBinding(directoryFD int, name string) ([]byte, uint32, error) {
	fd, err := syscall.Openat(directoryFD, name, syscall.O_RDONLY|syscall.O_NOFOLLOW, 0)
	if err != nil {
		return nil, 0, err
	}
	defer syscall.Close(fd)
	var info syscall.Stat_t
	if err = syscall.Fstat(fd, &info); err != nil {
		return nil, 0, err
	}
	if info.Mode&syscall.S_IFMT != syscall.S_IFREG {
		return nil, 0, fail("generated binding is not a regular file: %s", name)
	}
	var data []byte
	buffer := make([]byte, 1024*1024)
	for {
		count, readErr := syscall.Read(fd, buffer)
		if count > 0 {
			data = append(data, buffer[:count]...)
		}
		if readErr != nil {
			return nil, 0, readErr
		}
		if count == 0 {
			break
		}
	}
	return data, info.Mode, nil
}

func normalize(data []byte, spec bindingSpec) ([]byte, error) {
	canonicalPrefix := []byte("// \tprotoc        ")
	compilerPattern := regexp.MustCompile(`^// \tprotoc[ \t]+(?:\(unknown\)|v[0-9]+\.[0-9]+\.[0-9]+)$`)
	if spec.grpc {
		canonicalPrefix = []byte("// - protoc             ")
		compilerPattern = regexp.MustCompile(`^// - protoc[ \t]+(?:\(unknown\)|v[0-9]+\.[0-9]+\.[0-9]+)$`)
	}
	canonical := append(append([]byte{}, canonicalPrefix...), []byte(canonicalVersion)...)
	lines := bytes.SplitAfter(data, []byte{'\n'})
	text := func(line []byte) []byte {
		if len(line) > 0 && line[len(line)-1] == '\n' {
			return line[:len(line)-1]
		}
		return line
	}
	generated, compiler, source := []int{}, []int{}, []int{}
	for index, line := range lines {
		lineText := text(line)
		if bytes.Equal(lineText, spec.generated) {
			generated = append(generated, index)
		}
		if bytes.Equal(lineText, spec.source) {
			source = append(source, index)
		}
		if compilerPattern.Match(lineText) {
			compiler = append(compiler, index)
		}
	}
	if len(generated) != 1 || len(compiler) != 1 || len(source) != 1 {
		return nil, fail("unexpected generated header shape in %s", spec.name)
	}
	compilerText := text(lines[compiler[0]])
	if !bytes.Equal(compilerText, spec.unknown) && !bytes.Equal(compilerText, canonical) {
		return nil, fail("compiler marker is not canonical or unknown in %s", spec.name)
	}
	if !(generated[0] < compiler[0] && compiler[0] < source[0] && source[0] < 64) {
		return nil, fail("generated header ordering is invalid in %s", spec.name)
	}
	terminator := []byte{}
	if len(lines[compiler[0]]) > 0 && lines[compiler[0]][len(lines[compiler[0]])-1] == '\n' {
		terminator = []byte{'\n'}
	}
	lines[compiler[0]] = append(append([]byte{}, canonical...), terminator...)
	return bytes.Join(lines, nil), nil
}

func randomName(prefix string) string {
	var random [12]byte
	if _, err := rand.Read(random[:]); err != nil {
		panic(err)
	}
	return fmt.Sprintf(".%s.%x", prefix, random)
}

func writeStaged(directoryFD int, name string, data []byte, mode uint32) (string, error) {
	for attempt := 0; attempt < 32; attempt++ {
		temporary := randomName(name + ".normalize")
		fd, err := syscall.Openat(directoryFD, temporary, syscall.O_WRONLY|syscall.O_CREAT|syscall.O_EXCL|syscall.O_NOFOLLOW, 0600)
		if err == syscall.EEXIST {
			continue
		}
		if err != nil {
			return "", err
		}
		writeErr := error(nil)
		if writeErr = syscall.Fchmod(fd, mode&07777); writeErr == nil {
			for len(data) > 0 {
				count, err := syscall.Write(fd, data)
				if err != nil {
					writeErr = err
					break
				}
				if count == 0 {
					writeErr = errors.New("short write")
					break
				}
				data = data[count:]
			}
		}
		syscall.Close(fd)
		if writeErr != nil {
			syscall.Unlinkat(directoryFD, temporary)
			return "", writeErr
		}
		return temporary, nil
	}
	return "", errors.New("could not allocate a staging file")
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintf(os.Stderr, "usage: %s BINDING_ROOT\n", os.Args[0])
		os.Exit(64)
	}
	root, err := filepath.Abs(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	rootFD, err := openDirectoryChain(root)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer syscall.Close(rootFD)
	terrabaseFD, err := syscall.Openat(rootFD, "terrabase", syscall.O_RDONLY|syscall.O_DIRECTORY|syscall.O_NOFOLLOW, 0)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer syscall.Close(terrabaseFD)
	versionFD, err := syscall.Openat(terrabaseFD, "v1", syscall.O_RDONLY|syscall.O_DIRECTORY|syscall.O_NOFOLLOW, 0)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer syscall.Close(versionFD)

	original := make(map[string][]byte)
	modes := make(map[string]uint32)
	normalized := make(map[string][]byte)
	for _, spec := range specs {
		data, mode, readErr := readBinding(versionFD, spec.name)
		if readErr != nil {
			fmt.Fprintln(os.Stderr, readErr)
			os.Exit(1)
		}
		original[spec.name], modes[spec.name] = data, mode
	}
	for _, spec := range specs {
		normalized[spec.name], err = normalize(original[spec.name], spec)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}

	temporary := make(map[string]string)
	backups := make(map[string]string)
	installed := []string{}
	cleanup := func() {
		for _, name := range installed {
			_ = syscall.Unlinkat(versionFD, name)
		}
		for _, spec := range specs {
			if backup := backups[spec.name]; backup != "" {
				_ = syscall.Renameat(versionFD, backup, versionFD, spec.name)
			}
			if staged := temporary[spec.name]; staged != "" {
				_ = syscall.Unlinkat(versionFD, staged)
			}
		}
	}
	for _, spec := range specs {
		temporary[spec.name], err = writeStaged(versionFD, spec.name, normalized[spec.name], modes[spec.name])
		if err != nil {
			cleanup()
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	for _, spec := range specs {
		backup := randomName(spec.name + ".backup")
		if err = syscall.Renameat(versionFD, spec.name, versionFD, backup); err != nil {
			cleanup()
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		backups[spec.name] = backup
	}
	for _, spec := range specs {
		if err = syscall.Renameat(versionFD, temporary[spec.name], versionFD, spec.name); err != nil {
			cleanup()
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		installed = append(installed, spec.name)
	}
	for _, spec := range specs {
		_ = syscall.Unlinkat(versionFD, backups[spec.name])
	}
}
