import json
import re
import textwrap
from pathlib import Path

root = Path(__file__).resolve().parents[2]
producer = root / "src/TerraBase/Features/Sql/SqlSocketEndpoint.cs"
match = re.search(r'Description\("""\n(.*?)\n\s*"""\);', producer.read_text(), re.DOTALL)
if match is None:
    raise ValueError("the SQL WebSocket producer description was not found")
description = textwrap.dedent(match.group(1)).strip()
snapshot = json.loads((root / "docs/terrabase/sql/websocket-session.json").read_text())
snapshot["connection"] = description
for sdk in ("dotnet", "go"):
    target = root / f"sdk/{sdk}/contracts/terrabase/sql/websocket-session.json"
    target.write_text(json.dumps(snapshot, indent=2) + "\n")
    print(target.relative_to(root))
target = root / "sdk/dotnet/contracts/terrabase/sql-websocket.md"
target.write_text("# SQL WebSocket contract\n\n"
                  "Generated by scripts/sdk/export-sql-contracts.py from "
                  "src/TerraBase/Features/Sql/SqlSocketEndpoint.cs.\n\n"
                  + description + "\n\n"
                  "Recorded exchanges: [sql/websocket-session.json](sql/websocket-session.json).\n")
print(target.relative_to(root))

errors = (root / "src/TerraBase/Features/Sql/SqlErrors.cs").read_text()
codes = dict(re.findall(r'public const string (\w+) = "([^"\n]+)";', errors))
states = dict(re.findall(r'^        (\w+) => "([A-Z0-9]{5})",', errors, re.MULTILINE))
for names, state in re.findall(r'^        ((?:\w+ or )+\w+) => "([A-Z0-9]{5})",', errors, re.MULTILINE):
    states.update(dict.fromkeys(names.split(" or "), state))
statuses = {}
for names, status in re.findall(r'^        ([\w ]+) => StatusCodes.Status(\d+)[A-Za-z]+,', errors, re.MULTILINE):
    statuses.update(dict.fromkeys(names.split(" or "), int(status)))
error_snapshot = {"source": "src/TerraBase/Features/Sql/SqlErrors.cs", "codes": [
    {"code": code, "sqlstate": states.get(name, "0A000"), "status": statuses.get(name, 400)}
    for name, code in codes.items() if name != "StaleRowMessage"
]}
for sdk in ("dotnet", "go"):
    target = root / f"sdk/{sdk}/contracts/terrabase/sql/error-codes.json"
    target.write_text(json.dumps(error_snapshot, indent=2) + "\n")
    print(target.relative_to(root))
