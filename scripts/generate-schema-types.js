#!/usr/bin/env node
/** Generate TypeScript document read and ID types from terrascale.schema.json. */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { normalizeSchema, validateSchema } from "../src/schema.js";
/** @import { CollectionSchema, FieldDef, SchemaJson } from "../src/schema.js" */

/**
 * @typedef {object} GenerateSchemaTypesOptions
 * @property {string} [importPath]
 */

/**
 * Generate deterministic source for the supplied schema object or JSON text.
 *
 * @param {SchemaJson | string} input
 * @param {GenerateSchemaTypesOptions} [options]
 * @returns {string}
 */
export function generateSchemaTypes(input, options = {}) {
  const schema = normalizeSchema(
    typeof input === "string"
      ? /** @type {SchemaJson} */ (JSON.parse(input))
      : input,
  );
  validateSchema(schema);
  const importPath = options.importPath ?? "@terrascale/sdk";
  const lines = [
    "// Generated by scripts/generate-schema-types.js. Do not edit.",
    "// Source: terrascale.schema.json.",
    "// Pure local field declarations; catalog plan/apply is not implemented.",
    `import type { EntityId, DatabaseValue } from ${JSON.stringify(importPath)};`,
    "",
  ];
  for (const collection of schema.collections) {
    lines.push(...generateCollection(collection), "");
  }
  lines.push("export interface TerraScaleCollections {");
  for (const collection of schema.collections)
    lines.push(
      `  readonly ${collection.name}: ${typeName(collection.name)}Document;`,
    );
  lines.push(
    "}",
    "",
    "export type TerraScaleCollectionName = keyof TerraScaleCollections;",
    "",
  );
  return `${lines.join("\n")}\n`;
}

/**
 * @param {CollectionSchema} collection
 * @returns {readonly string[]}
 */
function generateCollection(collection) {
  const name = typeName(collection.name);
  const id = `${name}Id`;
  const singular = singularTypeName(name);
  const lines = [
    `export type ${id} = EntityId;`,
    "",
    `export interface ${name}Document {`,
  ];
  for (const field of collection.fields) {
    lines.push(
      `  readonly ${propertyName(field.name)}${field.required ? "" : "?"}: ${fieldType(field)} | Extract<DatabaseValue, { readonly type: "null" }>;`,
    );
  }
  lines.push("}", "", `export type ${name} = ${name}Document;`);
  if (singular !== name) {
    lines.push(
      `export type ${singular}Id = ${id};`,
      `export type ${singular}Document = ${name}Document;`,
      `export type ${singular} = ${name}Document;`,
    );
  }
  return lines;
}

/**
 * @param {FieldDef} field
 * @returns {string}
 */
function fieldType(field) {
  return `Extract<DatabaseValue, { readonly type: ${JSON.stringify(field.type)} }>`;
}

/**
 * @param {string} name
 * @returns {string}
 */
function typeName(name) {
  const words = name.split(/[^A-Za-z0-9]+/u).filter(Boolean);
  const value = words
    .map((word) => word[0]?.toUpperCase() + word.slice(1))
    .join("");
  return value.length === 0
    ? "Collection"
    : /^[0-9]/u.test(value)
      ? `Collection${value}`
      : value;
}

/**
 * @param {string} name
 * @returns {string}
 */
function singularTypeName(name) {
  if (name.endsWith("ies") && name.length > 3) return `${name.slice(0, -3)}y`;
  if (name.endsWith("ses") && name.length > 3) return name.slice(0, -2);
  if (name.endsWith("s") && !name.endsWith("ss") && name.length > 1)
    return name.slice(0, -1);
  return name;
}

/**
 * @param {string} name
 * @returns {string}
 */
function propertyName(name) {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/u;

/** @returns {Promise<void>} */
async function run() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const args = process.argv.slice(2);
  if (args.includes("--help") || args.includes("-h")) {
    process.stdout.write(
      "Usage: generate-schema-types.js [schema.json] [output.ts] [--check|--stdout]\n",
    );
    return;
  }
  const language = valueAfter(args, "--language");
  if (language !== undefined && language !== "typescript" && language !== "ts")
    throw new Error(
      `Unsupported schema codegen language ${JSON.stringify(language)}`,
    );
  const positional = args.filter(
    (argument, index) =>
      !argument.startsWith("-") &&
      args[index - 1] !== "--language" &&
      args[index - 1] !== "--schema" &&
      args[index - 1] !== "--out",
  );
  const source =
    valueAfter(args, "--schema") ??
    positional[0] ??
    path.join(root, "terrascale.schema.json");
  const output =
    valueAfter(args, "--out") ??
    positional[1] ??
    path.join(root, "src", "generated", "schema-types.ts");
  const sourceText = await readFile(path.resolve(source), "utf8");
  const generated = generateSchemaTypes(sourceText);
  if (args.includes("--stdout")) {
    process.stdout.write(generated);
    return;
  }
  if (args.includes("--check")) {
    const current = await readFile(path.resolve(output), "utf8").catch(
      () => undefined,
    );
    if (current !== generated)
      throw new Error(`${output} is out of date; regenerate schema types`);
    return;
  }
  await writeFile(path.resolve(output), generated, "utf8");
  process.stdout.write(`Wrote ${output}\n`);
}

/**
 * @param {readonly string[]} args
 * @param {string} flag
 * @returns {string | undefined}
 */
function valueAfter(args, flag) {
  const index = args.indexOf(flag);
  return index >= 0 ? args[index + 1] : undefined;
}

const entry = process.argv[1] ? path.resolve(process.argv[1]) : "";
if (entry === path.resolve(fileURLToPath(import.meta.url))) await run();
