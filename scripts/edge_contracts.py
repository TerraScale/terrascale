#!/usr/bin/env python3
"""Generate the Go SDK's origin-qualified edge route pin."""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path


def fail(message: str) -> "NoReturn":
    raise SystemExit(f"edge contracts: {message}")


def read_json(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        fail(f"cannot read {path}: {error}")


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    repo = Path(__file__).resolve().parent.parent
    source = Path(os.environ.get("EDGE_CONTRACT_SOURCE", "contracts/edge/v1"))
    if not source.is_absolute():
        source = repo / source
    manifest = read_json(source / "manifest.json")
    if manifest.get("schemaVersion") != 1 or manifest.get("contractVersion") != "v1":
        fail("manifest identity is not schemaVersion 1 / v1")
    if manifest.get("origin") != "edge":
        fail("manifest origin is not edge")
    artifacts = {item.get("path"): item for item in manifest.get("artifacts", [])}
    for name in ("openapi.json", "route-source.json"):
        if name not in artifacts:
            fail(f"manifest omits {name}")
        actual = digest(source / name)
        if actual != artifacts[name].get("sha256"):
            fail(f"{name} SHA-256 does not match manifest")
    route_source = read_json(source / "route-source.json")
    if route_source.get("origin") != "edge" or route_source.get("schemaVersion") != 1:
        fail("route source identity is invalid")
    routes = route_source.get("routes")
    if not isinstance(routes, list) or not routes:
        fail("route source has no routes")
    lines = [
        "// Code generated by scripts/edge_contracts.py; DO NOT EDIT.",
        "package sdk",
        "",
        "// EdgeContractRoute identifies an origin-qualified edge operation.",
        "type EdgeContractRoute struct {",
        "\tOperationID string",
        "\tMethod string",
        "\tPath string",
        "}",
        "",
        "const (",
        'EdgeContractVersion = "v1"',
        f'EdgeContractOpenAPISHA256 = "{digest(source / "openapi.json")}"',
        ")",
        "",
        "var EdgeContractRoutes = []EdgeContractRoute{",
    ]
    for route in routes:
        if not all(isinstance(route.get(field), str) and route[field] for field in ("operationId", "method", "path")):
            fail("route source has an incomplete route")
        lines.append(
            f'\t{{OperationID: "{route["operationId"]}", Method: "{route["method"]}", Path: "{route["path"]}"}},'
        )
    lines.extend(["}", ""])
    (repo / "edge_contract.go").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
