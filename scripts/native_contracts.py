#!/usr/bin/env python3
"""Pin and verify exact native producer source artifacts, without publication."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ARTIFACTS = {
    "client-openapi.json": (
        "crates/tb-server/assets/client-openapi.json",
        "2c8fc075bb2714de6f0ba10756f903e09e4d2a43ecaa63b2135ccb2042545a52",
    ),
    "atomic_vectors.json": (
        "crates/tb-server/tests/support/document/atomic_vectors.json",
        "4ce4286b6e2eeae4ee15dec83f788f33cffdba7606a49021ec81afe0a4a9e816",
    ),
}
ROOT = Path(__file__).resolve().parent.parent
BUNDLE = ROOT / "contracts" / "native"
MAX_ARTIFACT_BYTES = 8 << 20


def regular_bytes(path):
    if path.is_symlink() or not path.is_file():
        raise ValueError(f"expected a regular file: {path}")
    with path.open("rb") as stream:
        data = stream.read(MAX_ARTIFACT_BYTES + 1)
    if len(data) > MAX_ARTIFACT_BYTES:
        raise ValueError(f"artifact exceeds byte limit: {path}")
    return data


def writable(path):
    for candidate in [path, *path.parents]:
        if candidate.is_symlink():
            raise ValueError(f"refusing a symlink write target: {candidate}")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def verified_artifacts(source=None):
    result = {}
    for name, (producer_path, expected) in ARTIFACTS.items():
        path = source / producer_path if source is not None else BUNDLE / name
        data = regular_bytes(path)
        if digest(data) != expected:
            raise ValueError(f"producer SHA-256 mismatch: {path}")
        result[name] = data
    return result


def manifest_bytes(spec):
    manifest = {
        "schema_version": 1,
        "contract_version": spec["info"]["version"],
        "producer": "terrabase",
        "qualification": "source-artifacts-only",
        "artifacts": [
            {"path": name, "producer_path": producer_path, "sha256": sha}
            for name, (producer_path, sha) in ARTIFACTS.items()
        ],
    }
    return (json.dumps(manifest, indent=2) + "\n").encode()


def go_string(value):
    return json.dumps(value, ensure_ascii=False)


def model_name(content):
    schema = content.get("application/json", {}).get("schema", {})
    return schema.get("$ref", "").removeprefix("#/components/schemas/") or schema.get("type", "")


def model_fields(schema):
    names = set(schema.get("properties", {}))
    for alternative in schema.get("oneOf", []):
        names.update(model_fields(alternative))
    return sorted(names)


def formatted_go(source):
    return subprocess.run(
        ["gofmt"], input=source.encode(), stdout=subprocess.PIPE,
        stderr=subprocess.PIPE, check=True,
    ).stdout


def generated_bytes(spec):
    version = go_string(spec["info"]["version"])
    openapi_sha = go_string(ARTIFACTS["client-openapi.json"][1])
    vectors_sha = go_string(ARTIFACTS["atomic_vectors.json"][1])
    header = "// Code generated by scripts/native_contracts.py; DO NOT EDIT.\npackage sdk\n\n"
    output = header + """// ContractOperation describes an operation in the pinned native producer OpenAPI.
type ContractOperation struct {
    OperationID string
    Method string
    Path string
    RequestModel string
    ResponseModel string
}

// ContractRoute identifies one native producer HTTP route.
type ContractRoute struct {
    Method string
    Path string
    OperationID string
}

// ContractModel describes the possible JSON properties in a native schema.
type ContractModel struct {
    Name string
    Fields []string
}

""" + f"""const (
    ContractVersion = {version}
    ContractOpenAPISHA256 = {openapi_sha}
    ContractAtomicVectorsSHA256 = {vectors_sha}
)

"""
    operations = []
    for path, methods in spec["paths"].items():
        for method, operation in methods.items():
            if method not in {"get", "post", "put", "patch", "delete", "head", "options"}:
                continue
            request = model_name(operation.get("requestBody", {}).get("content", {}))
            response = model_name(operation.get("responses", {}).get("200", {}).get("content", {}))
            operations.append((operation["operationId"], method.upper(), path, request, response))
    operations.sort()
    output += "var ContractOperations = []ContractOperation{\n"
    for operation in operations:
        output += "    {" + ", ".join(go_string(v) for v in operation) + "},\n"
    output += "}\n\nvar ContractRoutes = []ContractRoute{\n"
    for operation_id, method, path, _, _ in sorted(operations, key=lambda v: (v[2], v[1])):
        output += "    {" + ", ".join(go_string(v) for v in (method, path, operation_id)) + "},\n"
    output += "}\n\nvar ContractModels = []ContractModel{\n"
    for name, schema in sorted(spec["components"]["schemas"].items()):
        fields = ", ".join(go_string(v) for v in model_fields(schema))
        output += f"    {{{go_string(name)}, []string{{{fields}}}}},\n"
    output += "}\n"
    pins = header + f"""const (
    pinnedContractVersion = {version}
    pinnedOpenAPISHA256 = {openapi_sha}
    pinnedAtomicVectorsSHA256 = {vectors_sha}
)
"""
    return {"contract.go": formatted_go(output), "generated_contract_test.go": formatted_go(pins)}


def run():
    parser = argparse.ArgumentParser(description=__doc__)
    options = parser.add_mutually_exclusive_group()
    options.add_argument("--source", type=Path, help="explicit TerraBase source root to pin")
    options.add_argument("--check", action="store_true", help="verify committed artifacts and metadata")
    args = parser.parse_args()
    artifacts = verified_artifacts(args.source)
    spec = json.loads(artifacts["client-openapi.json"])
    if spec.get("openapi") != "3.1.0":
        raise ValueError("expected producer OpenAPI 3.1.0")
    outputs = {
        BUNDLE / "manifest.json": manifest_bytes(spec),
        **{ROOT / path: data for path, data in generated_bytes(spec).items()},
    }
    if args.source is not None:
        outputs.update({BUNDLE / name: data for name, data in artifacts.items()})
        for path in outputs:
            writable(path)
        for path, data in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print("Pinned exact native producer source artifacts; runtime/publication remain unqualified.")
    else:
        for path, data in outputs.items():
            if regular_bytes(path) != data:
                raise ValueError(f"stale committed native artifact or metadata: {path}")
        print("Native producer artifact SHA-256 and generated metadata verified.")


if __name__ == "__main__":
    try:
        run()
    except (OSError, ValueError, KeyError, TypeError, subprocess.CalledProcessError) as error:
        print(f"native contracts: {error}", file=sys.stderr)
        sys.exit(1)
