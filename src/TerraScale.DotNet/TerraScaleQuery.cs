using System.Globalization;
using System.Text;

namespace TerraScale.DotNet;

/// <summary>
/// Small immutable builder for TerraScale repository TQL queries.
/// </summary>
public sealed record TerraScaleQuery
{
    private TerraScaleQuery(
        string collection,
        IReadOnlyList<string> predicates,
        IReadOnlyList<string> orderings,
        int? skipCount,
        int? takeCount)
    {
        Collection = collection;
        Predicates = predicates;
        Orderings = orderings;
        SkipCount = skipCount;
        TakeCount = takeCount;
    }

    /// <summary>
    /// Collection selected by the query.
    /// </summary>
    public string Collection { get; private init; }

    /// <summary>
    /// Predicate expressions generated by this builder.
    /// </summary>
    public IReadOnlyList<string> Predicates { get; private init; }

    /// <summary>
    /// Ordering expressions generated by this builder.
    /// </summary>
    public IReadOnlyList<string> Orderings { get; private init; }

    /// <summary>
    /// Number of matching documents to skip.
    /// </summary>
    public int? SkipCount { get; private init; }

    /// <summary>
    /// Maximum number of matching documents to return.
    /// </summary>
    public int? TakeCount { get; private init; }

    /// <summary>
    /// Starts a query against a collection.
    /// </summary>
    public static TerraScaleQuery From(string collection) =>
        new(
            RequireIdentifier(collection, nameof(collection)),
            [],
            [],
            skipCount: null,
            takeCount: null);

    /// <summary>
    /// Adds an equality predicate.
    /// </summary>
    public TerraScaleQuery WhereEqual<TValue>(string field, TValue value) =>
        AddPredicate($"{RequireIdentifier(field, nameof(field))} = {FormatValue(value)}");

    /// <summary>
    /// Adds an inequality predicate.
    /// </summary>
    public TerraScaleQuery WhereNotEqual<TValue>(string field, TValue value) =>
        AddPredicate($"{RequireIdentifier(field, nameof(field))} != {FormatValue(value)}");

    /// <summary>
    /// Adds a greater-than predicate.
    /// </summary>
    public TerraScaleQuery WhereGreaterThan<TValue>(string field, TValue value) =>
        AddPredicate($"{RequireIdentifier(field, nameof(field))} > {FormatValue(value)}");

    /// <summary>
    /// Adds a greater-than-or-equal predicate.
    /// </summary>
    public TerraScaleQuery WhereGreaterThanOrEqual<TValue>(string field, TValue value) =>
        AddPredicate($"{RequireIdentifier(field, nameof(field))} >= {FormatValue(value)}");

    /// <summary>
    /// Adds a less-than predicate.
    /// </summary>
    public TerraScaleQuery WhereLessThan<TValue>(string field, TValue value) =>
        AddPredicate($"{RequireIdentifier(field, nameof(field))} < {FormatValue(value)}");

    /// <summary>
    /// Adds a less-than-or-equal predicate.
    /// </summary>
    public TerraScaleQuery WhereLessThanOrEqual<TValue>(string field, TValue value) =>
        AddPredicate($"{RequireIdentifier(field, nameof(field))} <= {FormatValue(value)}");

    /// <summary>
    /// Adds an in-list predicate.
    /// </summary>
    public TerraScaleQuery WhereIn<TValue>(string field, IEnumerable<TValue> values)
    {
        ArgumentNullException.ThrowIfNull(values);
        var formattedValues = values.Select(FormatValue).ToArray();
        if (formattedValues.Length == 0)
        {
            throw new ArgumentException("At least one value is required.", nameof(values));
        }

        return AddPredicate(
            $"{RequireIdentifier(field, nameof(field))} in ({string.Join(", ", formattedValues)})");
    }

    /// <summary>
    /// Adds an ascending or descending ordering.
    /// </summary>
    public TerraScaleQuery OrderBy(string field, bool descending = false) =>
        this with
        {
            Orderings = [.. Orderings, $"{RequireIdentifier(field, nameof(field))} {(descending ? "desc" : "asc")}"]
        };

    /// <summary>
    /// Sets the number of matching documents to skip.
    /// </summary>
    public TerraScaleQuery Skip(int count)
    {
        if (count < 0)
        {
            throw new ArgumentOutOfRangeException(nameof(count), "Skip must be greater than or equal to zero.");
        }

        return this with { SkipCount = count };
    }

    /// <summary>
    /// Sets the maximum number of matching documents to return.
    /// </summary>
    public TerraScaleQuery Take(int count)
    {
        if (count <= 0)
        {
            throw new ArgumentOutOfRangeException(nameof(count), "Take must be greater than zero.");
        }

        return this with { TakeCount = count };
    }

    /// <summary>
    /// Renders this builder to a TQL string.
    /// </summary>
    public string ToTql()
    {
        var builder = new StringBuilder()
            .Append("from ")
            .Append(Collection);

        if (Predicates.Count > 0)
        {
            builder
                .Append(" where ")
                .AppendJoin(" and ", Predicates);
        }

        if (Orderings.Count > 0)
        {
            builder
                .Append(" order by ")
                .AppendJoin(", ", Orderings);
        }

        return builder.ToString();
    }

    /// <inheritdoc />
    public override string ToString() => ToTql();

    private TerraScaleQuery AddPredicate(string predicate) =>
        this with { Predicates = [.. Predicates, predicate] };

    private static string RequireIdentifier(string value, string parameterName)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(value, parameterName);
        var trimmed = value.Trim();
        foreach (var character in trimmed)
        {
            if (!char.IsLetterOrDigit(character) &&
                character is not '_' and not '-' and not '.')
            {
                throw new ArgumentException(
                    "Identifiers may only contain letters, digits, underscores, hyphens, and dots.",
                    parameterName);
            }
        }

        return trimmed;
    }

    private static string FormatValue<TValue>(TValue value) =>
        value switch
        {
            null => "null",
            string stringValue => $"'{EscapeString(stringValue)}'",
            char character => $"'{EscapeString(character.ToString())}'",
            bool boolean => boolean ? "true" : "false",
            DateTimeOffset dateTimeOffset => $"'{EscapeString(dateTimeOffset.ToString("O", CultureInfo.InvariantCulture))}'",
            DateTime dateTime => $"'{EscapeString(dateTime.ToString("O", CultureInfo.InvariantCulture))}'",
            Guid guid => $"'{guid:D}'",
            byte or sbyte or short or ushort or int or uint or long or ulong or float or double or decimal =>
                Convert.ToString(value, CultureInfo.InvariantCulture) ?? "null",
            IFormattable formattable => $"'{EscapeString(formattable.ToString(null, CultureInfo.InvariantCulture))}'",
            _ => $"'{EscapeString(value.ToString() ?? string.Empty)}'"
        };

    private static string EscapeString(string value) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("'", "\\'", StringComparison.Ordinal);
}
