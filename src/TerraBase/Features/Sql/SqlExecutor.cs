/// <summary>
/// Generated integer keys of one transaction, in order, so a replay of its statements generates the same keys
/// (docs/terrabase/sql/relational-sql.md section 5).
/// </summary>
internal sealed class SqlKeys
{
    private readonly List<long> _keys = [];
    private int _next;

    public int Count => _keys.Count;

    /// <summary>Forgets keys generated by statements that were undone.</summary>
    public void Truncate(int count)
    {
        _keys.RemoveRange(count, _keys.Count - count);
        _next = count;
    }

    /// <summary>Starts a replay: the next keys are the logged ones, then new ones.</summary>
    public void Rewind() => _next = 0;

    /// <summary>The logged key at this position, or a new one from <paramref name="generate"/>.</summary>
    public long Next(Func<long> generate)
    {
        if (_next == _keys.Count)
        {
            _keys.Add(generate());
        }

        return _keys[_next++];
    }
}

/// <summary>
/// The net document bytes a transaction's writes added, measured when the storage quota needs it, the rows it wrote and
/// their operation units, billed once it commits, and the table definitions it read, so its statements read each one once.
/// </summary>
/// <param name="Measure">Whether to measure.</param>
internal sealed class SqlTally(bool Measure)
{
    public bool Measure { get; } = Measure;

    public long Delta { get; set; }

    /// <summary>Rows written: each insert, update or delete of one row.</summary>
    public int Writes { get; set; }

    /// <summary>Operation units of the rows written (<see cref="OperationUnits"/>): a stored row's, one for a delete.</summary>
    public long WriteUnits { get; set; }

    /// <summary>Operation telemetry emitted only after this transaction commits, never during replay.</summary>
    public Dictionary<(string Collection, string Kind), int> Operations { get; } = [];

    /// <summary>Definitions by table name, null for no SQL table; DDL of the table removes its entry.</summary>
    public Dictionary<string, SqlTableDefinition?> Tables { get; } = [with(StringComparer.Ordinal)];
}

/// <summary>Runs one statement in a storage transaction the caller commits; writes go through the document service.</summary>
internal sealed class SqlExecutor(IDocumentService documents, IMemoryBudget memory, TimeProvider time, SqlReadCache reads, string? database)
{
    private static readonly SqlResult Empty = new([], [], 0, null);
    private static readonly DateTimeOffset KeyEpoch = new(2026, 1, 1, 0, 0, 0, TimeSpan.Zero);

    public async ValueTask<SqlOutcome> ExecuteAsync(
        IStorageTransaction transaction, ParsedSql statement, SqlCommand command, SqlKeys keys, SqlTally tally, bool describe,
        CancellationToken cancellationToken)
    {
        // All transports share this boundary, before parameters reach the engine or any document is written.
        if (command.Args.Concat(command.Named.Values).Any(value => value.Kind == SqlValueKind.Real && !double.IsFinite(value.Real)))
        {
            return SqlErrors.NonFinite;
        }

        return statement switch
        {
            ReadSql read => await ReadAsync(transaction, read, command, tally, describe, null, cancellationToken).ConfigureAwait(false),
            PragmaSql pragma => await PragmaAsync(transaction, pragma, tally, cancellationToken).ConfigureAwait(false),
            // A described write runs nothing: its columns are its RETURNING list.
            InsertSql { Returning: { } returning } insert when describe => await ReturningColumnsAsync(transaction, insert.Table, returning, tally, cancellationToken).ConfigureAwait(false),
            ChangeSql { Returning: { } returning } change when describe => await ReturningColumnsAsync(transaction, change.Table, returning, tally, cancellationToken).ConfigureAwait(false),
            InsertSql insert => await InsertAsync(transaction, insert, command, keys, tally, cancellationToken).ConfigureAwait(false),
            ChangeSql change => await ChangeAsync(transaction, change, command, tally, cancellationToken).ConfigureAwait(false),
            CreateTableSql create => await CreateAsync(transaction, create, tally, cancellationToken).ConfigureAwait(false),
            AddColumnSql add => await AddColumnAsync(transaction, add, tally, cancellationToken).ConfigureAwait(false),
            DropTableSql drop => await DropAsync(transaction, drop, tally, cancellationToken).ConfigureAwait(false),
            CreateIndexSql index => await CreateIndexAsync(transaction, index, tally, cancellationToken).ConfigureAwait(false),
            DropIndexSql drop => await DropIndexAsync(transaction, drop, tally, cancellationToken).ConfigureAwait(false),
            _ => SqlErrors.Error("this statement is not supported here"),
        };
    }

    private async ValueTask<SqlOutcome> CreateAsync(IStorageTransaction transaction, CreateTableSql create, SqlTally tally, CancellationToken cancellationToken)
    {
        tally.Tables.Remove(create.Name);
        if (await transaction.GetCollectionAsync(create.Name, cancellationToken).ConfigureAwait(false) is not null)
        {
            return create.IfNotExists && await SqlTable.ReadAsync(transaction, create.Name, cancellationToken).ConfigureAwait(false) is not null
                ? Empty
                : SqlErrors.Error("already exists: a table or a document collection has this name");
        }

        var collection = new CollectionInfo(create.Name, time.GetUtcNow().ToUnixTimeMilliseconds(), EntityIds.New(time).ToString());
        await transaction.CreateCollectionAsync(collection, cancellationToken).ConfigureAwait(false);
        await SqlTable.WriteAsync(transaction, create.Name, create.Table, cancellationToken).ConfigureAwait(false);
        if (create.Unique.Count > 0)
        {
            await transaction.SetUniqueConstraintsAsync(create.Name, create.Unique, reindex: false, cancellationToken).ConfigureAwait(false);
        }

        return Empty;
    }

    private static async ValueTask<SqlOutcome> AddColumnAsync(IStorageTransaction transaction, AddColumnSql add, SqlTally tally, CancellationToken cancellationToken)
    {
        if (await TableAsync(transaction, add.Table, tally, cancellationToken).ConfigureAwait(false) is not { } table)
        {
            return SqlErrors.Error("no such table");
        }

        if (table.Columns.Any(column => column.Name.Equals(add.Column.Name, StringComparison.OrdinalIgnoreCase)))
        {
            return SqlErrors.Error("already exists: the table has a column with this name");
        }

        if (table.Columns.Count >= SqlTable.MaxColumns)
        {
            return SqlErrors.Error("a table has 1 to 256 columns");
        }

        var sql = WithColumn(table.Sql, add.Definition);
        if (table.Sql is not null && sql is null)
        {
            return SqlErrors.Error("cannot preserve the table's catalog definition");
        }

        tally.Tables.Remove(add.Table);
        await SqlTable.WriteAsync(transaction, add.Table, table with
        {
            Columns = [.. table.Columns, add.Column],
            Sql = sql,
        }, cancellationToken).ConfigureAwait(false);
        return Empty;
    }

    private static string? WithColumn(string? sql, ColumnDef column)
    {
        try
        {
            if (sql is not null && new Parser().ParseSql(sql, new SQLiteDialect()) is [Statement.CreateTable { Element: var create }])
            {
                var text = (create with { Columns = [.. create.Columns, column] }).ToSql();
                return new Parser().ParseSql(text, new SQLiteDialect()) is [Statement.CreateTable] ? text : null;
            }
        }
        catch (ParserException)
        {
            // Older catalog text can be reconstructed from the stored columns instead.
        }
        catch (TokenizeException)
        {
            // The structured definition remains authoritative.
        }

        return null;
    }

    private static async ValueTask<SqlOutcome> DropAsync(IStorageTransaction transaction, DropTableSql drop, SqlTally tally, CancellationToken cancellationToken)
    {
        if (await TableAsync(transaction, drop.Name, tally, cancellationToken).ConfigureAwait(false) is null)
        {
            return drop.IfExists ? Empty : SqlErrors.Error("no such table");
        }

        tally.Tables.Remove(drop.Name);
        // Use retained bytes before and after: collection statistics omit hidden uniqueness conflicts.
        var before = tally.Measure ? await transaction.GetStoredDocumentBytesAsync(cancellationToken).ConfigureAwait(false) : 0;
        await transaction.DropCollectionAsync(drop.Name, cancellationToken).ConfigureAwait(false);
        if (tally.Measure)
        {
            tally.Delta += await transaction.GetStoredDocumentBytesAsync(cancellationToken).ConfigureAwait(false) - before;
        }

        return Empty;
    }

    // A secondary index over the columns; a UNIQUE one also declares a unique key of the same name, checked against the
    // table's rows. The secondary index names it database-wide, as SQLite names indexes.
    private static async ValueTask<SqlOutcome> CreateIndexAsync(IStorageTransaction transaction, CreateIndexSql create, SqlTally tally, CancellationToken cancellationToken)
    {
        if (await TableAsync(transaction, create.Table, tally, cancellationToken).ConfigureAwait(false) is not { } table)
        {
            return SqlErrors.Error("no such table");
        }

        var fields = new List<DocumentField>(create.Columns.Count);
        foreach (var name in create.Columns)
        {
            if (table.Columns.FirstOrDefault(column => column.Name.Equals(name, StringComparison.OrdinalIgnoreCase)) is not { } column
                || !DocumentField.TryParse(column.Name, out var field))
            {
                return SqlErrors.Error("no such column");
            }

            fields.Add(field);
        }

        var constraints = await transaction.GetUniqueConstraintsAsync(create.Table, cancellationToken).ConfigureAwait(false);
        if ((await transaction.ListIndexesAsync(cancellationToken).ConfigureAwait(false)).Any(index => index.Name == create.Name)
            || constraints.Any(constraint => constraint.Name == create.Name))
        {
            return create.IfNotExists ? Empty : SqlErrors.Error("an index with this name already exists");
        }

        if (create.Unique)
        {
            if (constraints.Count == UniqueKeys.MaxConstraints)
            {
                return SqlErrors.Error("a table has at most 32 UNIQUE constraints and indexes");
            }

            try
            {
                UniqueConstraint key = new(create.Name, [.. fields.Select(field => field.Path)]);
                await transaction.SetUniqueConstraintsAsync(create.Table, [.. constraints, key], reindex: true, cancellationToken).ConfigureAwait(false);
            }
            catch (UniqueConstraintException)
            {
                return SqlErrors.Constraint("UNIQUE", "the table's rows already hold duplicate values for a UNIQUE index");
            }
        }

        _ = await transaction.CreateIndexAsync(new IndexDefinition(create.Name, create.Table, fields), cancellationToken).ConfigureAwait(false);
        return Empty;
    }

    private static async ValueTask<SqlOutcome> DropIndexAsync(IStorageTransaction transaction, DropIndexSql drop, SqlTally tally, CancellationToken cancellationToken)
    {
        // Only an index on a SQL table: indexes of document collections belong to the indexes API.
        if ((await transaction.ListIndexesAsync(cancellationToken).ConfigureAwait(false)).FirstOrDefault(index => index.Name == drop.Name) is not { } index
            || await TableAsync(transaction, index.Collection, tally, cancellationToken).ConfigureAwait(false) is null)
        {
            return drop.IfExists ? Empty : SqlErrors.Error("no such index");
        }

        var constraints = await transaction.GetUniqueConstraintsAsync(index.Collection, cancellationToken).ConfigureAwait(false);
        if (constraints.Any(constraint => constraint.Name == drop.Name))
        {
            try
            {
                await transaction.SetUniqueConstraintsAsync(
                    index.Collection, [.. constraints.Where(constraint => constraint.Name != drop.Name)], reindex: true, cancellationToken).ConfigureAwait(false);
            }
            catch (UniqueConstraintException)
            {
                // Rows a concurrent region's write hid under another key: they still conflict.
                return SqlErrors.Constraint("UNIQUE", "the table's rows hold duplicate values for another UNIQUE key");
            }
        }

        _ = await transaction.DropIndexAsync(drop.Name, cancellationToken).ConfigureAwait(false);
        return Empty;
    }

    // The engine read of `read`: its tables' definitions, its parameters bound, its rows converted. `keyed` names the
    // table whose rows also expose their document id (`_id`), for UPDATE and DELETE. A shared read (SqlReadCache) compiles its
    // own parse of its text, once per set of table definitions; one that reads the catalog embeds its rows and is never kept.
    private async ValueTask<SqlOutcome> ReadAsync(
        IStorageTransaction transaction, ReadSql read, SqlCommand command, SqlTally tally, bool describe, string? keyed, CancellationToken cancellationToken)
    {
        var tables = new Dictionary<string, SqlTableDefinition>(StringComparer.Ordinal);
        foreach (var name in read.Tables)
        {
            if (await TableAsync(transaction, name, tally, cancellationToken).ConfigureAwait(false) is not { } table)
            {
                return SqlErrors.Error("no such table");
            }

            tables[name] = table;
        }

        if (Bind(read.Params, command) is not { } parameters)
        {
            return SqlErrors.Error(string.Create(CultureInfo.InvariantCulture, $"the statement takes {read.Params.Count} arguments"));
        }

        var definitions = read is { Shared: not null, Catalog.Count: 0 } && database is not null
            ? string.Join('\n', read.Tables.Select(name => JsonSerializer.Serialize(tables[name], Hosting.TerraBaseJsonContext.Default.SqlTableDefinition)))
            : null;
        SqlProgram program;
        try
        {
            if (definitions is null || reads.Template(database!, read.Shared!, definitions, describe, keyed) is not { } template)
            {
                using var reservation = memory.TryReserve(MemoryLane.Foreground, SqlAffinityResolver.ReservationBytes);
                if (reservation is null)
                {
                    return new SqlError("SQLITE_NOMEM", "the server's memory budget is exhausted; retry");
                }

                var own = read.Shared is not { } text ? read
                    : SqlParse.Parse(text) is ReadSql fresh ? fresh : throw new InvalidOperationException("a shared read parses again as a read");
                // The catalog relations it reads come first, as CTEs of their rows.
                if (own.Catalog.Count > 0)
                {
                    var catalog = await SqlCatalog.CtesAsync(transaction, own.Catalog, name => TableAsync(transaction, name, tally, cancellationToken), cancellationToken).ConfigureAwait(false);
                    own = own with { Query = own.Query with { With = new SqlParser.Ast.With(false, [.. catalog, .. own.Query.With?.CteTables ?? []]) } };
                }

                template = SqlRead.Compile(own, tables, parameters.Length, describe, keyed);
                if (definitions is not null)
                {
                    reads.Add(database!, read.Shared!, definitions, describe, keyed, template);
                }
            }

            program = SqlRead.Bind(template, parameters);
        }
        catch (FormatException error)
        {
            // The row guard needs a column of every joined item.
            return SqlErrors.Error(error.Message);
        }

        var result = await transaction.ExecuteSqlAsync(program, cancellationToken).ConfigureAwait(false);
        if (result.Truncated)
        {
            return SqlErrors.TooBig("a result holds at most 10000 rows and 8 MiB; add a LIMIT");
        }

        var rows = new List<IReadOnlyList<SqlValue>>(result.Rows.Count);
        foreach (var row in result.Rows)
        {
            var values = new SqlValue[row.Length];
            for (var i = 0; i < row.Length; i++)
            {
                switch (row[i])
                {
                    case long integer:
                        values[i] = SqlValue.Of(integer);
                        break;
                    case double real when !double.IsFinite(real):
                        return SqlErrors.NonFinite;
                    case double real:
                        values[i] = SqlValue.Of(real);
                        break;
                    case string text:
                        values[i] = SqlValue.Of(text);
                        break;
                    case null:
                        break;
                    default:
                        return SqlErrors.Error("blob values are not supported");
                }
            }

            rows.Add(values);
        }

        var types = SqlRead.DeclTypes(read, tables, result.Columns.Count);
        return new SqlResult([.. result.Columns.Select((name, i) => new SqlColumn(name, types[i]))], rows, 0, null);
    }

    /// <summary>
    /// One value per parameter: positional arguments by number, a named argument (with or without its prefix) over it;
    /// unbound parameters are NULL, as in SQLite. Null when more positional arguments than parameters arrive.
    /// </summary>
    private static object?[]? Bind(IReadOnlyList<string?> names, SqlCommand command)
    {
        if (command.Args.Count > names.Count)
        {
            return null;
        }

        var values = new object?[names.Count];
        for (var i = 0; i < names.Count; i++)
        {
            var value = i < command.Args.Count ? command.Args[i] : SqlValue.Null;
            if (names[i] is { } name && (command.Named.TryGetValue(name, out var named) || command.Named.TryGetValue(name[1..], out named)))
            {
                value = named;
            }

            values[i] = value.Kind switch
            {
                SqlValueKind.Integer => value.Integer,
                SqlValueKind.Real => value.Real,
                SqlValueKind.Text => value.Text,
                _ => null,
            };
        }

        return values;
    }

    private async ValueTask<SqlOutcome> InsertAsync(
        IStorageTransaction transaction, InsertSql insert, SqlCommand command, SqlKeys keys, SqlTally tally, CancellationToken cancellationToken)
    {
        if (await TableAsync(transaction, insert.Table, tally, cancellationToken).ConfigureAwait(false) is not { } table)
        {
            return SqlErrors.Error("no such table");
        }

        var constraints = await transaction.GetUniqueConstraintsAsync(insert.Table, cancellationToken).ConfigureAwait(false);
        var primaryTarget = insert.ConflictColumns is null || SameKey(insert.ConflictColumns, table.PrimaryKey);
        var uniqueTargets = constraints.Where(constraint => insert.ConflictColumns is null
            || (constraint.Normalization == "none" && SameKey(insert.ConflictColumns, constraint.Fields))).Select(constraint => constraint.Name).ToHashSet(StringComparer.Ordinal);
        if (insert.ConflictColumns is not null && !primaryTarget && uniqueTargets.Count == 0)
        {
            return SqlErrors.Error("ON CONFLICT target does not match a PRIMARY KEY or UNIQUE constraint");
        }

        var targets = new List<SqlColumnDefinition>();
        foreach (var name in insert.Columns ?? [.. table.Columns.Select(column => column.Name)])
        {
            if (table.Columns.FirstOrDefault(column => column.Name.Equals(name, StringComparison.OrdinalIgnoreCase)) is not { } column
                || targets.Contains(column))
            {
                return SqlErrors.Error("INSERT names each column of the table at most once");
            }

            targets.Add(column);
        }

        // DEFAULT VALUES has no input columns: every column takes its default or generated key.
        if (insert.Source is null)
        {
            targets.Clear();
        }

        IReadOnlyList<IReadOnlyList<SqlValue>> rows = [[]];
        if (insert.Source is { } source)
        {
            switch (await ReadAsync(transaction, source with { Params = insert.Params }, command, tally, false, null, cancellationToken).ConfigureAwait(false))
            {
                case SqlError error:
                    return error;
                case SqlResult result:
                    rows = result.Rows;
                    break;
            }
        }

        if (rows.Count > SqlWrite.MaxRows)
        {
            return SqlErrors.TooBig("a statement writes at most 1024 rows");
        }

        // An INTEGER key, or a SERIAL one (Postgres's auto-increment types, which ORM migration tables declare), is generated when left out.
        var integerKey = table.PrimaryKey is [var only] && Column(table, only) is var key && (key.Affinity == SqlAffinity.Integer || SqlTable.IsSerial(key.Type))
            ? only
            : null;
        (List<SqlColumn>? Columns, List<string> Names)? returned = insert.Returning is { } returning ? Returned(table, returning) : null;
        if (returned is { Columns: null })
        {
            return SqlErrors.Error("no such column");
        }

        var output = new List<IReadOnlyList<SqlValue>>();
        long affected = 0;
        long? lastRowid = null;
        foreach (var row in rows)
        {
            if (row.Count != targets.Count)
            {
                return SqlErrors.Error(string.Create(CultureInfo.InvariantCulture, $"the rows have {row.Count} values for {targets.Count} columns"));
            }

            var values = new Dictionary<string, SqlValue>(StringComparer.Ordinal);
            foreach (var column in table.Columns)
            {
                var index = targets.IndexOf(column);
                var value = index >= 0 ? row[index] : column.Default is { } fallback ? SqlWrite.Default(fallback) : SqlValue.Null;
                values[column.Name] = SqlWrite.Apply(column.Affinity, value);
            }

            if (insert.Mode == InsertMode.Replace)
            {
                foreach (var column in table.Columns.Where(column => column.Name != integerKey && column.NotNull && values[column.Name].Kind == SqlValueKind.Null && column.Default is not null))
                {
                    values[column.Name] = SqlWrite.Apply(column.Affinity, SqlWrite.Default(column.Default!.Value));
                }
            }

            // Defaults bypass the engine read; validate the final values before key or document serialization.
            if (values.Values.Any(value => value.Kind == SqlValueKind.Real && !double.IsFinite(value.Real)))
            {
                return SqlErrors.NonFinite;
            }

            if (integerKey is not null)
            {
                if (values[integerKey].Kind == SqlValueKind.Null)
                {
                    values[integerKey] = SqlValue.Of(await GenerateAsync(transaction, insert.Table, keys, cancellationToken).ConfigureAwait(false));
                }

                if (values[integerKey].Kind != SqlValueKind.Integer)
                {
                    return new SqlError("SQLITE_MISMATCH", "an INTEGER PRIMARY KEY holds integers only");
                }
            }

            if (table.Columns.FirstOrDefault(column => column.NotNull && values[column.Name].Kind == SqlValueKind.Null) is not null)
            {
                if (insert.Mode == InsertMode.Ignore)
                {
                    continue;
                }

                return SqlErrors.Constraint("NOTNULL", "a NOT NULL column has no value");
            }

            if (Key(table, values) is not { } id)
            {
                return new SqlError("SQLITE_MISMATCH", "a primary key is an integer or text, and a key at most 256 characters without control characters");
            }

            var body = Document(values);
            if (insert.Mode != InsertMode.Plain)
            {
                if (values.TryGetValue("id", out var identity) && identity.Kind == SqlValueKind.Text && identity.Text == id
                    && constraints.Any(constraint => constraint.Fields.Contains("id", StringComparer.Ordinal)))
                {
                    return SqlErrors.Error("conflict handling for UNIQUE keys containing an elided document id is not supported");
                }

                // A UNIQUE rejection faults the storage transaction: find conflicts before any document mutation.
                var primary = await transaction.GetVersionAsync(insert.Table, id, cancellationToken).ConfigureAwait(false) is { Deleted: false };
                IReadOnlyList<(string Constraint, string Id)> conflicts = constraints.Count == 0 ? []
                    : await transaction.GetUniqueConflictsAsync(insert.Table, body, SqlWrite.MaxRows + 1, cancellationToken).ConfigureAwait(false);
                if (conflicts.Count > SqlWrite.MaxRows)
                {
                    return SqlErrors.TooBig("a statement resolves at most 1024 unique conflicts");
                }

                if ((insert.Mode == InsertMode.Ignore && (primary || conflicts.Count > 0))
                    || (insert.Mode == InsertMode.DoNothing && ((primary && primaryTarget) || conflicts.Any(conflict => uniqueTargets.Contains(conflict.Constraint)))))
                {
                    continue;
                }

                if (insert.Mode == InsertMode.Replace)
                {
                    foreach (var replaced in conflicts.Select(conflict => conflict.Id).Where(replaced => replaced != id).Distinct(StringComparer.Ordinal))
                    {
                        var delete = new DeleteOperation(insert.Table, replaced, new Precondition(null, false, false));
                        if (await ApplyAsync(transaction, delete, replaced, tally, cancellationToken).ConfigureAwait(false) is { } rejected)
                        {
                            return rejected;
                        }
                    }
                }
            }

            var absent = insert.Mode != InsertMode.Replace;
            var put = new PutOperation(insert.Table, id, body, absent ? Precondition.Absent : new Precondition(null, false, false));
            if (await ApplyAsync(transaction, put, id, tally, cancellationToken, absent).ConfigureAwait(false) is { } refused)
            {
                return refused;
            }

            affected++;
            lastRowid = integerKey is null ? null : values[integerKey].Integer;
            if (returned is { Names: var names })
            {
                output.Add([.. names.Select(name => values[name])]);
            }
        }

        return new SqlResult(returned?.Columns ?? [], output, affected, lastRowid);
    }

    private static bool SameKey(IReadOnlyList<string> target, IReadOnlyList<string> key) =>
        target.Count > 0 && target.Count == key.Count && target.Distinct(StringComparer.OrdinalIgnoreCase).Count() == target.Count
        && target.ToHashSet(StringComparer.OrdinalIgnoreCase).SetEquals(key);

    private async ValueTask<SqlOutcome> ChangeAsync(
        IStorageTransaction transaction, ChangeSql change, SqlCommand command, SqlTally tally, CancellationToken cancellationToken)
    {
        if (await TableAsync(transaction, change.Table, tally, cancellationToken).ConfigureAwait(false) is not { } table)
        {
            return SqlErrors.Error("no such table");
        }

        var columns = new List<SqlColumnDefinition>();
        foreach (var (name, _, _) in change.Assignments)
        {
            if (table.Columns.FirstOrDefault(column => column.Name.Equals(name, StringComparison.OrdinalIgnoreCase)) is not { } column || columns.Contains(column))
            {
                return SqlErrors.Error("SET assigns each column of the table at most once");
            }

            if (table.PrimaryKey.Contains(column.Name))
            {
                return SqlErrors.Error("a PRIMARY KEY column cannot be updated: delete the row and insert it again");
            }

            columns.Add(column);
        }

        var read = await ReadAsync(transaction, change.Rows with { Params = change.Params }, command, tally, false, change.Table, cancellationToken).ConfigureAwait(false);
        if (read is not SqlResult { Rows: var rows })
        {
            return read;
        }

        if (rows.Count > SqlWrite.MaxRows)
        {
            return SqlErrors.TooBig("a statement writes at most 1024 rows");
        }

        (List<SqlColumn>? Columns, List<string> Names)? returned = change.Returning is { } returning ? Returned(table, returning) : null;
        if (returned is { Columns: null })
        {
            return SqlErrors.Error("no such column");
        }

        // With RETURNING the read ends with every column (*) as it was; an update's new values replace the assigned ones.
        var output = new List<IReadOnlyList<SqlValue>>();
        foreach (var row in rows)
        {
            var id = row[0].Text!;
            var after = returned is null ? null : table.Columns.Select((column, index) => (column.Name, Value: row[row.Count - table.Columns.Count + index]))
                .ToDictionary(StringComparer.Ordinal);
            DocumentOperation operation;
            if (change.IsDelete)
            {
                operation = new DeleteOperation(change.Table, id, new Precondition(null, false, false));
            }
            else
            {
                var ops = new List<PatchOpRequest>();
                var value = 1;
                for (var i = 0; i < columns.Count; i++)
                {
                    var (_, op, by) = change.Assignments[i];
                    var path = "/" + columns[i].Name;
                    var set = op is "set" or "inc" ? SqlWrite.Apply(columns[i].Affinity, row[value++]) : SqlValue.Null;
                    if (set.Kind == SqlValueKind.Real && !double.IsFinite(set.Real))
                    {
                        return SqlErrors.NonFinite;
                    }

                    after?[columns[i].Name] = set;
                    // Only an INTEGER NOT NULL column is a counter; elsewhere c = c + 1 is the computed value (NULL stays NULL).
                    if (op == "inc" && columns[i] is { Affinity: SqlAffinity.Integer, NotNull: true })
                    {
                        ops.Add(new PatchOpRequest("inc", path, default, SqlWrite.Json(SqlValue.Of(by))));
                    }
                    else if (set.Kind == SqlValueKind.Null)
                    {
                        if (columns[i].NotNull)
                        {
                            return SqlErrors.Constraint("NOTNULL", "a NOT NULL column has no value");
                        }

                        ops.Add(new PatchOpRequest("unset", path, default, default));
                    }
                    else
                    {
                        ops.Add(new PatchOpRequest("set", path, SqlWrite.Json(set), default));
                    }
                }

                if (DocumentPatch.CheckOps(ops) is not DocumentPatch patch)
                {
                    return SqlErrors.Error("the new values do not form a valid change");
                }

                operation = new PatchOperation(change.Table, id, patch, new Precondition(null, false, false));
            }

            if (await ApplyAsync(transaction, operation, id, tally, cancellationToken).ConfigureAwait(false) is { } refused)
            {
                return refused;
            }

            if (returned is { Names: var names })
            {
                output.Add([.. names.Select(name => after![name])]);
            }
        }

        return new SqlResult(returned?.Columns ?? [], output, rows.Count, null);
    }

    // The document service's refusal of one operation, in SQLite's vocabulary, or null when it applied. Each storage call
    // costs a hop to the database's worker, so bytes already known are not read: none before a write to an `absent`
    // row, none after a delete, and a patch's stored document after it. A stored row bills its units, as a document
    // put does.
    private async ValueTask<SqlError?> ApplyAsync(
        IStorageTransaction transaction, DocumentOperation operation, string id, SqlTally tally, CancellationToken cancellationToken, bool absent = false)
    {
        var before = tally.Measure && !absent ? await transaction.GetDocumentBytesAsync(operation.Collection, id, cancellationToken).ConfigureAwait(false) : 0;
        var outcome = await documents.ApplyAsync(transaction, operation, cancellationToken).ConfigureAwait(false);
        if (outcome is OperationResult result)
        {
            var after = operation is DeleteOperation ? 0
                : result.Document is { } stored ? stored.Length
                : await transaction.GetDocumentBytesAsync(operation.Collection, id, cancellationToken).ConfigureAwait(false);
            tally.Writes++;
            tally.WriteUnits += operation is DeleteOperation ? 1 : OperationUnits.Of(after);
            var key = (operation.Collection, operation switch { DeleteOperation => "delete", PatchOperation => "patch", _ => "put" });
            tally.Operations[key] = tally.Operations.GetValueOrDefault(key) + 1;
            if (tally.Measure)
            {
                tally.Delta += after - before;
            }
        }

        return Refusal(outcome);
    }

    private static SqlError? Refusal(ApplyOutcome outcome) =>
        outcome switch
        {
            OperationResult => null,
            DocumentRejected { Error: var error } => error switch
            {
                Conflict { Code: "unique_violation" } => SqlErrors.Constraint("UNIQUE", "a UNIQUE column or columns already hold this value"),
                Validation { Code: "schema_validation_failed" } => SqlErrors.Constraint("CHECK", "the row does not satisfy the collection schema"),
                PreconditionFailed => SqlErrors.Constraint("PRIMARYKEY", "a row with this primary key exists"),
                PayloadTooLarge or Unavailable { Code: "capacity" } => SqlErrors.TooBig("a transaction writes at most 1024 rows and 2 MiB"),
                _ => SqlErrors.Error("the write was refused"),
            },
        };

    // A new INTEGER PRIMARY KEY below 2^53: milliseconds since 2026-01-01 times 4096 plus 12 random bits, retried on a
    // local collision. Logged in `keys`, so a replayed transaction reuses it.
    private async ValueTask<long> GenerateAsync(IStorageTransaction transaction, string table, SqlKeys keys, CancellationToken cancellationToken)
    {
        for (var attempt = 0; ; attempt++)
        {
            var key = keys.Next(() => ((long)(time.GetUtcNow() - KeyEpoch).TotalMilliseconds * 4096) + Random.Shared.Next(4096));
            if (attempt == 7 || await transaction.GetAsync(table, key.ToString(CultureInfo.InvariantCulture), cancellationToken).ConfigureAwait(false) is null)
            {
                return key;
            }
        }
    }

    private static async ValueTask<SqlTableDefinition?> TableAsync(IStorageTransaction transaction, string name, SqlTally tally, CancellationToken cancellationToken)
    {
        if (!tally.Tables.TryGetValue(name, out var table))
        {
            table = await SqlTable.ReadAsync(transaction, name, cancellationToken).ConfigureAwait(false);
            tally.Tables[name] = table;
        }

        return table;
    }

    private static SqlColumnDefinition Column(SqlTableDefinition table, string name) => table.Columns.First(column => column.Name == name);

    // A RETURNING list's result columns and the table columns they read; no columns when one names no column of the table.
    private static (List<SqlColumn>? Columns, List<string> Names) Returned(SqlTableDefinition table, IReadOnlyList<SqlReturning> returning)
    {
        var columns = new List<SqlColumn>();
        var names = new List<string>();
        foreach (var item in returning)
        {
            var matched = item.Column is null ? table.Columns : [.. table.Columns.Where(column => column.Name.Equals(item.Column, StringComparison.OrdinalIgnoreCase))];
            if (matched.Count == 0)
            {
                return (null, names);
            }

            foreach (var column in matched)
            {
                columns.Add(new SqlColumn(item.Alias ?? column.Name, column.Type));
                names.Add(column.Name);
            }
        }

        return (columns, names);
    }

    private static async ValueTask<SqlOutcome> ReturningColumnsAsync(
        IStorageTransaction transaction, string name, IReadOnlyList<SqlReturning> returning, SqlTally tally, CancellationToken cancellationToken) =>
        await TableAsync(transaction, name, tally, cancellationToken).ConfigureAwait(false) is not { } table ? SqlErrors.Error("no such table")
        : Returned(table, returning) is { Columns: { } columns } ? new SqlResult(columns, [], 0, null)
        : SqlErrors.Error("no such column");

    // As SQLite answers: no rows for a missing table or index (SqlCatalog).
    private static async ValueTask<SqlOutcome> PragmaAsync(IStorageTransaction transaction, PragmaSql pragma, SqlTally tally, CancellationToken cancellationToken)
    {
        if (pragma.Kind == PragmaKind.ReadUncommitted)
        {
            return new SqlResult([new SqlColumn("read_uncommitted", null)], [[SqlValue.Of(0)]], 0, null);
        }

        List<SqlColumn> columns = [.. SqlCatalog.Columns(pragma.Kind).Select(name => new SqlColumn(name, null))];
        return pragma.Kind == PragmaKind.TempTableInfo
            ? new SqlResult(columns, [], 0, null)
            : new SqlResult(columns, await SqlCatalog.PragmaAsync(transaction, pragma.Kind, pragma.Table!, name => TableAsync(transaction, name, tally, cancellationToken), cancellationToken).ConfigureAwait(false), 0, null);
    }

    // The document id: a single INTEGER or TEXT key's canonical value, otherwise the JSON array of the key values, or a
    // new ULID without a key.
    private static string? Key(SqlTableDefinition table, Dictionary<string, SqlValue> values)
    {
        string id;
        if (table.PrimaryKey.Count == 0)
        {
            id = EntityIds.New().ToString();
        }
        else if (table.PrimaryKey is [var single] && Column(table, single).Affinity is SqlAffinity.Integer or SqlAffinity.Text)
        {
            // INTEGER and TEXT affinity keep one storage class, so the value alone is the id.
            var value = values[single];
            id = value.Kind switch
            {
                SqlValueKind.Integer => value.Integer.ToString(CultureInfo.InvariantCulture),
                SqlValueKind.Text => value.Text!,
                _ => "",
            };
        }
        else
        {
            // Other affinities hold 1 and '1' as different keys: the JSON array of the values keeps their type.
            using var buffer = new MemoryStream();
            using (var writer = new Utf8JsonWriter(buffer))
            {
                writer.WriteStartArray();
                foreach (var column in table.PrimaryKey)
                {
                    SqlWrite.Write(writer, values[column]);
                }

                writer.WriteEndArray();
            }

            id = System.Text.Encoding.UTF8.GetString(buffer.ToArray());
        }

        return id is { Length: > 0 and <= 256 } && !id.Any(char.IsControl) ? id : null;
    }

    // Every column with a value; SQL NULL is a missing field.
    private static byte[] Document(Dictionary<string, SqlValue> values)
    {
        using var buffer = new MemoryStream();
        using (var writer = new Utf8JsonWriter(buffer))
        {
            writer.WriteStartObject();
            foreach (var (name, value) in values.Where(pair => pair.Value.Kind != SqlValueKind.Null))
            {
                writer.WritePropertyName(name);
                SqlWrite.Write(writer, value);
            }

            writer.WriteEndObject();
        }

        return buffer.ToArray();
    }
