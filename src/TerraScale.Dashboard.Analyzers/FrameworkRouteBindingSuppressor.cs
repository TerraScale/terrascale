using System;
using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

namespace TerraScale.Dashboard.Analyzers;

// The SDK binder implements framework HTTP parsing errors; dashboard source still uses native errors.
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class FrameworkRouteBindingSuppressor : DiagnosticSuppressor
{
    private static readonly SuppressionDescriptor FrameworkBinding = new(
        "TSDASH001", "RS0030", "The SDK-generated HTTP binder constructs framework parsing exceptions.");

    public override ImmutableArray<SuppressionDescriptor> SupportedSuppressions => [FrameworkBinding];

    public override void ReportSuppressions(SuppressionAnalysisContext context)
    {
        foreach (var diagnostic in context.ReportedDiagnostics)
        {
            var tree = diagnostic.Location.SourceTree;
            if (diagnostic.Id != "RS0030" || tree is null ||
                !("/" + tree.FilePath.Replace('\\', '/')).EndsWith(
                    "/Microsoft.AspNetCore.Http.RequestDelegateGenerator/Microsoft.AspNetCore.Http.RequestDelegateGenerator.RequestDelegateGenerator/GeneratedRouteBuilderExtensions.g.cs",
                    StringComparison.Ordinal))
            {
                continue;
            }

            var root = tree.GetRoot(context.CancellationToken);
            if (!root.GetLeadingTrivia().ToFullString().Contains("<auto-generated>"))
            {
                continue;
            }

            var node = root.FindNode(diagnostic.Location.SourceSpan).FirstAncestorOrSelf<ObjectCreationExpressionSyntax>();
            if (node is not null && context.GetSemanticModel(tree).GetSymbolInfo(node, context.CancellationToken).Symbol is IMethodSymbol constructor &&
                constructor.ContainingType.ToDisplayString() == "Microsoft.AspNetCore.Http.BadHttpRequestException")
            {
                context.ReportSuppression(Suppression.Create(FrameworkBinding, diagnostic));
            }
        }
    }
}
